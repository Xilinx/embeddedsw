/*************************************************************************************************/
/**
 * @brief	Resolve the slot to use within a sub-vault, without claiming it. Serves both
 *		the requested-slot path (ReqKeyId != 0) and the auto-assign path
 *		(ReqKeyId == 0). Callers resolve up front so a conflict is reported before
 *		any key material is created.
 *
 * @param	VaultId		Vault whose sub-vault is resolved. Caller must range-check
 *				against XASU_KM_MAX_VAULTS before calling.
 * @param	KeyType		Identifier of the key type being resolved. Caller must
 *				range-check against XKEYMANAGER_MAX_SUB_VAULTS before calling.
 * @param	ReqKeyId	Requested 1-based slot, or 0 to auto-assign the first free slot.
 * @param	SlotPtr		Updated with the resolved 1-based slot on success.
 *
 * @return
 *	- XASUFW_SUCCESS, when a slot is resolved.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, when the requested slot exceeds capacity or its
 *	  in-vault address cannot be resolved.
 *	- XASUFW_KEYMANAGER_KEY_SLOT_IN_USE, when the requested slot is occupied.
 *	- XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED, when the sub-vault has no free slots.
 *
 *************************************************************************************************/
static s32 XKeyManager_GetKeySlot(u8 VaultId, XAsu_KeyManagerSubVaultType KeyType, u16 ReqKeyId,
			u16 *SlotPtr)
{
	CREATE_VOLATILE(Status, XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED);
	const XKeyManager *KeyVaultPtr =
			(XKeyManager *)VaultManager.VaultInfo[VaultId].VaultBasePtr;
	XAsu_KeyManagerKeyMetadata *KeyObjectPtr =
			(XAsu_KeyManagerKeyMetadata *)XKeyManager_GetKeyObjectAddr(VaultId,
					(u8)KeyType, XKEYMANAGER_KEY_INDEX_OFFSET);
	u32 KeyObjectSize = XKeyManager_KeyObjectSizeLookup[KeyType];
	u16 SubVaultCapacity = 0U;
	u16 Slot = 0U;
	volatile u16 Index = 0U;

	if (ReqKeyId != 0U) {
		/**
		 * Requested slot: resolve its address, which the helper range-checks against the
		 * sub-vault capacity, then read the slot to confirm it is free.
		 */
		KeyObjectPtr = (XAsu_KeyManagerKeyMetadata *)XKeyManager_GetKeyObjectAddr(VaultId,
					(u8)KeyType, ReqKeyId);
		if (KeyObjectPtr == NULL) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}
		if (XASU_KM_GET_KEY_INDEX(KeyObjectPtr->CompositeKeyId) != 0U) {
			Status = XASUFW_KEYMANAGER_KEY_SLOT_IN_USE;
			goto END;
		}
		Slot = ReqKeyId;
		Status = XASUFW_SUCCESS;
	} else {
		/**
		 * Find the first free slot. A sub-vault of zero capacity resolves to a NULL
		 * base address and leaves the status at the seeded capacity error.
		 */
		if (KeyObjectPtr == NULL) {
			goto END;
		}
		SubVaultCapacity = KeyVaultPtr->SubVaultHeaders[KeyType].Capacity;
		for (Index = 0U; Index < SubVaultCapacity; Index++) {
			if (XASU_KM_GET_KEY_INDEX(KeyObjectPtr->CompositeKeyId) == 0U) {
				Slot = (Index + 1U);
				Status = XASUFW_SUCCESS;
				break;
			}
			KeyObjectPtr = (XAsu_KeyManagerKeyMetadata *)((u8 *)KeyObjectPtr +
					KeyObjectSize);
		}
	}

	if (Status == XASUFW_SUCCESS) {
		*SlotPtr = Slot;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function stores the provided key in the vault and updates the key identifier
 *		with the generated composite KeyId. In case of X.509 certificate, it also extracts
 *		the raw public key and stores it in the appropriate sub-vault based on the public
 *		key type, and updates the X.509 certificate object with the referenced raw key ID.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	AesInstancePtr	Pointer to the XAes instance for key unwrapping if the key is wrapped.
 * @param	KeyParams	Pointer to key manager parameters containing key metadata and
 *				key data address in KeyObjectAddr field.
 * @param	KeyIdPtr	Pointer to the output Key ID where the generated composite key
 *				identifier will be stored.
 * @param	SubSystemId	Subsystem ID for which the key is being stored.
 *
 * @return
 *	- XASUFW_SUCCESS, when the key is stored successfully in the vault.
 *	- XASUFW_FAILURE, in case of failure.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if input parameters are invalid, if the requested key
 *	  slot exceeds the sub-vault capacity, or if the certificate slot address cannot be
 *	  resolved while backfilling the raw key ID.
 *	- XASUFW_KEYMANAGER_KEY_NOT_FOUND, if the certificate slot no longer holds the key just
 *	  stored when the raw key ID is backfilled.
 *	- XASUFW_KEYMANAGER_INVALID_VAULT_ACCESS, if the subsystem cannot access the vault.
 *	- XASUFW_KEYMANAGER_VAULT_NOT_FOUND, if the vault does not exist.
 *	- XASUFW_KEYMANAGER_KEY_SLOT_IN_USE, if the requested key slot is already occupied,
 *	  packed with the operation-specific slot resolution error.
 *	- XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED, if the sub-vault has no free slot.
 *	- XASUFW_ERR_KEYWRAP_NOT_ENABLED, if wrapped key is used but keywrap feature is not enabled
 *	- XASUFW_X509_CERT_PARSE_FAIL, if X.509 certificate parsing fails.
 *	- XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL, if updating key vault fails.
 *	- XASUFW_KEYMANAGER_STORE_X509_RAW_KEY_ERROR, if resolving the raw key slot or storing the
 *	  raw key from the X.509 certificate fails.
 *	- XASUFW_AES_WRITE_KEY_FAILED, if writing AES key for unwrapping fails.
 *	- XASUFW_KEYMANAGER_GET_KEYOBJ_FAILED, if resolving key object for unwrapping fails.
 *	- XASUFW_KEYWRAP_AES_UNWRAPPED_KEY_ERROR, if unwrapping input key fails.
 *	- XASUFW_KEYMANAGER_INVALID_BUF_SIZE, if unwrapped key size exceeds maximum buffer size, or
 *	  if a PQC key's declared length disagrees with the length its parameter set defines for
 *	  the target sub-vault, the latter packed with the key vault update error.
 *	- XASUFW_DMA_COPY_FAIL, if the DMA transfer or the memory copy fails.
 *
 *************************************************************************************************/
s32 XKeyManager_StoreKeyInVault(XAsufw_Dma *DmaPtr, XAes *AesInstancePtr, const XAsu_KeyManagerParams *KeyParams,
				u32 *KeyIdPtr, u32 SubSystemId)
{
	/**
	 * Capture the start time of the key store operation, if performance
	 * measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_START(XASU_MODULE_KEYMANAGER_ID);

	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	CREATE_VOLATILE(DeleteStatus, XASUFW_FAILURE);
	s32 ClearStatus = XASUFW_FAILURE;
	X509_CertInfo CertInfo;
	u8 UnwrapOutBuf[XKEYMANAGER_MAX_UNWRAPPED_BUFF_OP_LEN_IN_BYTES];
	XKeyManager_X509KeyObject *X509KeyObjectPtr = NULL;
	volatile u32 *RawKeyIdVolatilePtr = NULL;
	u32 X509RawKeyId = 0U;
	XAsu_KeyManagerSubVaultType X509RawSubVault = XASU_INVALID_SUBVAULT_ID;
	u16 X509RawSlot = 0U;
	XAsu_AesKeyObject AesKeyObj;
	XAsu_KeyWrapParams KeyUnwrapParams;
	u64 LocalBuffAddr = 0U;
	u8 *RsaPubKeyData = NULL;
	u8 KeyType;
	u8 ReqKeyType;
	u8 VaultId;
	u16 ResolvedSlot = 0U;
	u32 OutDataLen = 0U;
	u32 KeyWrapUnwrapOutputLen = 0U;

	/** Validate input parameters. */
	if ((DmaPtr == NULL) || (KeyParams == NULL) || (KeyIdPtr == NULL)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Split the requested vault and key type out of the composite key ID. */
	ReqKeyType = XASU_KM_GET_KEY_TYPE(KeyParams->KeyMetadata.CompositeKeyId);
	VaultId = XASU_KM_GET_VAULT_ID(KeyParams->KeyMetadata.CompositeKeyId);

	/** Validate store-key parameters using the shared client/server validator. */
	Status = XAsu_KmValidateParams(KeyParams, XASU_KM_VALIDATE_FLOW_STORE,
				      (u8)XASU_INVALID_SUBVAULT_ID, 0U);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_INVALID_PARAM);
		goto END;
	}

	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	/** Validate vault exists and belongs to the subsystem. */
	if (VaultManager.VaultInfo[VaultId].VaultSize == 0U) {
		Status = XASUFW_KEYMANAGER_VAULT_NOT_FOUND;
		goto END;
	}

	if (VaultManager.VaultInfo[VaultId].SubSystemId != SubSystemId) {
		Status = XASUFW_KEYMANAGER_INVALID_VAULT_ACCESS;
		goto END;
	}

	KeyType = (u8)(ReqKeyType & ~XASU_KM_KEYTYPE_WRAPPED_BIT_MASK);

	/** For a PQC sub-vault, check the declared length against the parameter set. */
	Status = XKeyManager_ValidatePqcStoreKeyLength((XAsu_KeyManagerSubVaultType)KeyType,
			KeyParams);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
		goto END;
	}

	/** Resolve the target slot before unwrap or parse, so a slot conflict fails fast. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetKeySlot(VaultId, (XAsu_KeyManagerSubVaultType)KeyType,
		XASU_KM_GET_KEY_INDEX(KeyParams->KeyMetadata.CompositeKeyId), &ResolvedSlot);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
		goto END;
	}

	LocalBuffAddr = KeyParams->KeyObjectAddr;

	/* Check if wrapped key. */
	if ((ReqKeyType & XASU_KM_KEYTYPE_WRAPPED_BIT_MASK) == XASU_KM_KEYTYPE_WRAPPED_BIT_MASK) {
		if (AesInstancePtr == NULL) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}
#ifdef XASU_KEYWRAP_ENABLE
		/**
		 * Verify the key is not a wrapped RSA public key, as unwrap yields only the modulus,
		 * which cannot be repacked into the (PubExp || Modulus) vault layout.
		 */
		if ((ReqKeyType & ~XASU_KM_KEYTYPE_WRAPPED_BIT_MASK) ==
				(u8)XASU_RSA_PUB_SUBVAULT_ID) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}

		if (((KeyParams->AesKeyObj.KeySize != XASU_AES_KEY_SIZE_128_BITS) &&
		     (KeyParams->AesKeyObj.KeySize != XASU_AES_KEY_SIZE_256_BITS)) ||
		    (KeyParams->AesKeyObj.KeySrc >= XASU_AES_MAX_KEY_SOURCES)) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}

		KeyUnwrapParams.InputDataAddr = KeyParams->KeyObjectAddr;
		KeyUnwrapParams.OutputDataAddr = (u64)(UINTPTR)UnwrapOutBuf;
		KeyUnwrapParams.ExpoCompAddr = 0U;
		KeyUnwrapParams.KeyCompAddr = 0U;
		KeyUnwrapParams.OptionalLabelAddr = 0U;
		KeyUnwrapParams.InputDataLen = KeyParams->WrappedInputLen;
		KeyUnwrapParams.RsaKeySize = 0U;
		KeyUnwrapParams.OptionalLabelSize = 0U;
		KeyUnwrapParams.OutputDataLen = XKEYMANAGER_MAX_UNWRAPPED_BUFF_OP_LEN_IN_BYTES;
		KeyUnwrapParams.ActualOutputDataLenAddr = (u64)(UINTPTR)&KeyWrapUnwrapOutputLen;
		KeyUnwrapParams.AesKeySize = (u8)KeyParams->AesKeyObj.KeySize;
		KeyUnwrapParams.ShaType = 0U;
		KeyUnwrapParams.ShaMode = 0U;
		KeyUnwrapParams.AesKeyId = 0U;
		KeyUnwrapParams.RsaKeyId = 0U;

		AesKeyObj.KeySrc = KeyParams->AesKeyObj.KeySrc;
		if ((KeyParams->AesKeyObj.KeyAddress == 0U) && (KeyParams->AesKeyObj.KeyId != 0U)) {
			AesKeyObj.KeyAddress = 0U;
			AesKeyObj.KeyId = KeyParams->AesKeyObj.KeyId;
			Status = XKeyManager_UpdateAesKeyObjectFromVault(&AesKeyObj, SubSystemId,
								XASU_KEYMANAGER_AES_KEY_UNWRAP_USE_CASE);
			if (Status != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateErrorStatus(Status,
						XASUFW_KEYMANAGER_GET_KEYOBJ_FAILED);
				goto END;
			}
		} else if (KeyParams->AesKeyObj.KeyAddress != 0U) {
			AesKeyObj.KeyAddress = KeyParams->AesKeyObj.KeyAddress;
			AesKeyObj.KeySize = KeyUnwrapParams.AesKeySize;
		} else {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}
		/** Write AES key. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_WriteKey(AesInstancePtr, DmaPtr, &AesKeyObj);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_AES_WRITE_KEY_FAILED;
			goto END_KEY_CLR;
		}

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyWrap_UnwrapOp(&KeyUnwrapParams, AesInstancePtr, DmaPtr, &OutDataLen,
					XASU_KEYWRAP_AES_KWPUNWP);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_KEYWRAP_AES_UNWRAPPED_KEY_ERROR;
			goto END_KEY_CLR;
		}

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		if (OutDataLen != KeyParams->KeyMetadata.Length) {
			Status = XASUFW_KEYWRAP_AES_UNWRAPPED_KEY_ERROR;
			goto END_KEY_CLR;
		}

		LocalBuffAddr = (u64)(UINTPTR)UnwrapOutBuf;
#else
		Status = XASUFW_ERR_KEYWRAP_NOT_ENABLED;
		goto END;
#endif
	}

	/**
	 * Parse X.509 certificate if the key type is X.509.
	 * This extracts the public key, key usage, and other certificate information
	 * needed for storing the raw public key in the appropriate sub-vault.
	 */
	if (KeyType == (u8)XASU_X509_SUBVAULT_ID) {
		Status = X509_ParseCertificate(LocalBuffAddr, KeyParams->KeyMetadata.Length, &CertInfo);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_X509_CERT_PARSE_FAIL);
			goto END_KEY_CLR;
		}
	}

	/**
	 * An unwrapped RSA public key arrives as XAsu_RsaPubKeyComp (Keysize || Modulus || PubExp),
	 * but the vault object expects PubExp || Modulus. Repack into a scratch buffer in that order.
	 */
	if (ReqKeyType == (u8)XASU_RSA_PUB_SUBVAULT_ID) {

		/** Verify the modulus length fits the scratch buffer to prevent out-of-bounds write. */
		if (KeyParams->KeyMetadata.Length > XRSA_MAX_KEY_SIZE_IN_BYTES) {
			Status = XASUFW_KEYMANAGER_INVALID_BUF_SIZE;
			goto END_KEY_CLR;
		}

		RsaPubKeyData = (u8 *)(UINTPTR)XASUFW_CRYPTO_AUX_BUF_ADDR;

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		/** Pack the public exponent at the start of the scratch buffer. */
		Status = XAsufw_DmaXfr(DmaPtr,
						LocalBuffAddr + XKEYMANAGER_RSA_PUB_KEY_PUBEXP_OFFSET,
						(u64)(UINTPTR)RsaPubKeyData, XRSA_PUBEXP_SIZE_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_KEY_CLR;
		}

		/** Append the modulus after the public exponent in the scratch buffer. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
					LocalBuffAddr + XKEYMANAGER_RSA_PUB_KEY_MODULUS_OFFSET,
					(u64)(UINTPTR)&RsaPubKeyData[XRSA_PUBEXP_SIZE_IN_BYTES],
					KeyParams->KeyMetadata.Length, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_KEY_CLR;
		}

		LocalBuffAddr = (u64)(UINTPTR)RsaPubKeyData;
	}

	/** For X.509, resolve the raw public key slot too, before the certificate is written. */
	if (KeyType == (u8)XASU_X509_SUBVAULT_ID) {
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyManager_GetX509RawKeySubVault(&CertInfo, &X509RawSubVault);
		if (Status != XASUFW_SUCCESS) {
			goto END_KEY_CLR;
		}
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyManager_GetKeySlot(VaultId, X509RawSubVault, 0U, &X509RawSlot);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status,
					XASUFW_KEYMANAGER_STORE_X509_RAW_KEY_ERROR);
			goto END_KEY_CLR;
		}
	}

	/** Update the key vault with the provided key data at the resolved slot. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_UpdateKeyVault(DmaPtr,
					    (XAsu_KeyManagerSubVaultType)KeyType,
					    KeyParams, (u8 *)(UINTPTR)LocalBuffAddr,
					    ResolvedSlot, KeyIdPtr);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
		goto END_KEY_CLR;
	}

	/** Store X.509 raw public key to respective key vault. */
	if (KeyType == (u8)XASU_X509_SUBVAULT_ID) {
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyManager_StoreX509RawPublicKey(DmaPtr, KeyParams, &CertInfo,
							   X509RawSubVault, X509RawSlot,
							   &X509RawKeyId);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status,
							XASUFW_KEYMANAGER_STORE_X509_RAW_KEY_ERROR);
			/** - Delete the certificate so a failed store leaves no orphan. */
			DeleteStatus = XKeyManager_DeleteKey(*KeyIdPtr, SubSystemId);
			if (DeleteStatus != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateBufStatus(Status, DeleteStatus);
			}
			goto END_KEY_CLR;
		}

		/**
		 * Backfill the raw key ID into the just-stored certificate object using the
		 * computed slot address, so usage-count and epoch-expiry policy are not applied
		 * to this internal write.
		 */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		X509KeyObjectPtr = (XKeyManager_X509KeyObject *)
				XKeyManager_GetKeyObjectAddr(VaultId, KeyType, ResolvedSlot);

		/**
		 * Confirm the slot still holds the certificate just stored before writing to it,
		 * then write and read RawKeyId back through the volatile pointer, so a store the
		 * compiler elided or a glitch skipped is caught rather than folded away.
		 */
		if (X509KeyObjectPtr == NULL) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		} else if (X509KeyObjectPtr->Metadata.CompositeKeyId != *KeyIdPtr) {
			Status = XASUFW_KEYMANAGER_KEY_NOT_FOUND;
		} else {
			RawKeyIdVolatilePtr = (volatile u32 *)&X509KeyObjectPtr->RawKeyId;
			*RawKeyIdVolatilePtr = X509RawKeyId;
			if (*RawKeyIdVolatilePtr == X509RawKeyId) {
				Status = XASUFW_SUCCESS;
			} else {
				Status = XASUFW_KEYMANAGER_STORE_X509_RAW_KEY_ERROR;
			}
		}

		if (Status != XASUFW_SUCCESS) {
			/** - Delete the raw public key and the certificate, in reverse order. */
			DeleteStatus = XKeyManager_DeleteKey(X509RawKeyId, SubSystemId);
			if (DeleteStatus != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateBufStatus(Status, DeleteStatus);
			}
			ASSIGN_VOLATILE(DeleteStatus, XASUFW_FAILURE);
			DeleteStatus = XKeyManager_DeleteKey(*KeyIdPtr, SubSystemId);
			if (DeleteStatus != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateBufStatus(Status, DeleteStatus);
			}
			goto END_KEY_CLR;
		}
	}

	/**
	 * Measure and print the performance time for the key store operation, if
	 * performance measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_STOP(XASU_MODULE_KEYMANAGER_ID);

END_KEY_CLR:
	if ((ReqKeyType & XASU_KM_KEYTYPE_WRAPPED_BIT_MASK) == XASU_KM_KEYTYPE_WRAPPED_BIT_MASK) {
		ClearStatus = XAes_KeyClear(AesInstancePtr, AesKeyObj.KeySrc);
		if (ClearStatus != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, ClearStatus);
		}
	}
	/** Zeroize output data. */
	ASSIGN_VOLATILE(ClearStatus, XASUFW_FAILURE);
	ClearStatus = Xil_SecureZeroize(UnwrapOutBuf, XKEYMANAGER_MAX_UNWRAPPED_BUFF_OP_LEN_IN_BYTES);
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

END:
	return Status;
}

