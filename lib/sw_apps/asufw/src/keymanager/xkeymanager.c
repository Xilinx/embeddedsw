/**
 * @brief	Get the number of active RSA private keys in the ASU internal vault.
 *
 * @param	KeyType	Identifier of the RSA key type to query.
 *
 * @return	Number of active RSA private keys, or 0 if the vault is not found.
 *
 *************************************************************************************************/
u16 XKeyManager_GetAsuRsaActiveKeyCount(XAsu_KeyManagerSubVaultType KeyType)
{
	XKeyManager *KeyVaultPtr;
	u16 ActiveKeys = 0U;

	if(KeyType >= XKEYMANAGER_MAX_SUB_VAULTS) {
		goto END;
	}

	KeyVaultPtr = (XKeyManager *)VaultManager.VaultInfo[XKEYMANAGER_ASU_VAULT_ID].VaultBasePtr;
	if (KeyVaultPtr != NULL) {
		ActiveKeys = KeyVaultPtr->SubVaultHeaders[KeyType].ActiveKeys;
	}

END:
	return ActiveKeys;
}

/*************************************************************************************************/
/**
 * @brief	Fetch a pre-generated RSA key pair from the ASU internal vault and remove it.
 *			Copies the private key content to the destination buffer and deletes both the
 *			private and public keys from the vault.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	DestBuf		Pointer to the destination buffer.
 * @param	VaultId		Identifier of the vault to fetch the key from.
 * @param	KeyAddr		Destination address for DMA transfer (0 if vault storage).
 *
 * @return
 *	- XASUFW_SUCCESS, if key pair is fetched and removed successfully.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if input parameter is invalid.
 *	- XASUFW_KEYMANAGER_KEY_NOT_FOUND, if no active RSA key is available in the vault.
 *	- XASUFW_DMA_COPY_FAIL, if DMA transfer fails.
 *
 *************************************************************************************************/
s32 XKeyManager_FetchRsaKeyPairFromAsuVault(XAsufw_Dma *DmaPtr, u8 *DestBuf, u8 VaultId, u64 KeyAddr)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	XKeyManager *KeyVaultPtr = NULL;
	XAsu_KeyManagerKeyMetadata *KeyMetaPtr = NULL;
	XAsu_RsaKeyPairObject *SrcKeyPtr = NULL;
	XAsu_KeyManagerKeyMetadata *PvtKeyMetaPtr = NULL;
	u32 KeyObjSize;
	u32 CompositeKeyIds[XKEYMANAGER_ASYM_KEY_TYPE_COUNT] = {0U};
	u32 KeyLen;
	u8 *SubVaultBase;
	u64 DestAddr;
	u16 Capacity;
	u16 Index;
	XAsu_KeyManagerSubVaultType KeyType;
	u32 TypeIdx;

	/** Validate input parameters. */
	if ((DestBuf == NULL) || (DmaPtr == NULL)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	if (VaultId != XKEYMANAGER_ASU_VAULT_ID) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	KeyVaultPtr = (XKeyManager *)VaultManager.VaultInfo[VaultId].VaultBasePtr;
	if (KeyVaultPtr == NULL) {
		Status = XASUFW_FAILURE;
		goto END;
	}

	/** If no active RSA keys are available, error out. */
	if ((KeyVaultPtr->SubVaultHeaders[XASU_RSA_PVT_SUBVAULT_ID].ActiveKeys == 0U) ||
	    (KeyVaultPtr->SubVaultHeaders[XASU_RSA_PUB_SUBVAULT_ID].ActiveKeys == 0U)) {
		Status = XASUFW_KEYMANAGER_KEY_NOT_FOUND;
		goto END;
	}

	/** Phase 1: Find the first active key in each sub-vault and record composite IDs. */
	for (TypeIdx = 0U; TypeIdx < XKEYMANAGER_ASYM_KEY_TYPE_COUNT; TypeIdx++) {
		KeyType = (XAsu_KeyManagerSubVaultType)((TypeIdx == 0U) ? XASU_RSA_PVT_SUBVAULT_ID :
					    XASU_RSA_PUB_SUBVAULT_ID);
		KeyObjSize = XKeyManager_KeyObjectSizeLookup[KeyType];
		Capacity = KeyVaultPtr->SubVaultHeaders[KeyType].Capacity;
		SubVaultBase = (u8 *)KeyVaultPtr +
			       KeyVaultPtr->SubVaultHeaders[KeyType].Offset;

		for (Index = 0U; Index < Capacity; Index++) {
			KeyMetaPtr = (XAsu_KeyManagerKeyMetadata *)(SubVaultBase +
					(KeyObjSize * (u32)Index));
			if (XASU_KM_GET_KEY_INDEX(KeyMetaPtr->CompositeKeyId) != 0U) {
				CompositeKeyIds[TypeIdx] = KeyMetaPtr->CompositeKeyId;
				if (KeyType == XASU_RSA_PVT_SUBVAULT_ID) {
					PvtKeyMetaPtr = KeyMetaPtr;
				}
				break;
			}
		}
		if (Index == Capacity) {
			Status = XASUFW_KEYMANAGER_KEY_NOT_FOUND;
			goto END;
		}
	}

	/** Phase 2: Copy private key content to the destination. */
	if (KeyAddr != 0U) {
		SrcKeyPtr = (XAsu_RsaKeyPairObject *)((u8 *)PvtKeyMetaPtr +
				sizeof(XAsu_KeyManagerKeyMetadata));
		KeyLen = PvtKeyMetaPtr->Length;
		DestAddr = KeyAddr;

		/** Copy PubExp via DMA. */
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)&SrcKeyPtr->PubExp,
				       DestAddr, XRSA_PUBEXP_SIZE_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += XRSA_PUBEXP_SIZE_IN_BYTES;

		/** Copy Modulus via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->Modulus,
				       DestAddr, KeyLen, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += KeyLen;

		/** Copy PvtExp via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->PvtExp,
				       DestAddr, KeyLen, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += KeyLen;

		/** Copy Prime1 via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->Prime1,
				       DestAddr, XKEYMANAGER_HALF_KEY_LEN(KeyLen), 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += XKEYMANAGER_HALF_KEY_LEN(KeyLen);

		/** Copy Prime2 via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->Prime2,
				       DestAddr, XKEYMANAGER_HALF_KEY_LEN(KeyLen), 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += XKEYMANAGER_HALF_KEY_LEN(KeyLen);

		/** Copy DP via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->DP,
				       DestAddr, XKEYMANAGER_HALF_KEY_LEN(KeyLen), 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += XKEYMANAGER_HALF_KEY_LEN(KeyLen);

		/** Copy DQ via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->DQ,
				       DestAddr, XKEYMANAGER_HALF_KEY_LEN(KeyLen), 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
		DestAddr += XKEYMANAGER_HALF_KEY_LEN(KeyLen);

		/** Copy QInv via DMA. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       (u64)(UINTPTR)SrcKeyPtr->QInv,
				       DestAddr, XKEYMANAGER_HALF_KEY_LEN(KeyLen), 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END;
		}
	} else {
		/**
		 * For vault storage, copy the entire max-size
		 * structure to DestBuf.
		 */
		Status = Xil_SMemCpy(DestBuf,
			XRSA_MAX_KEY_OBJ_SIZE_IN_BYTES,
			(u8 *)PvtKeyMetaPtr + sizeof(XAsu_KeyManagerKeyMetadata),
			XRSA_MAX_KEY_OBJ_SIZE_IN_BYTES,
			XRSA_MAX_KEY_OBJ_SIZE_IN_BYTES);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_MEM_COPY_FAIL;
			goto END;
		}
	}

	/** On successful copy, delete both keys from the vault. */
	for (TypeIdx = 0U; TypeIdx < XKEYMANAGER_ASYM_KEY_TYPE_COUNT; TypeIdx++) {
		if (CompositeKeyIds[TypeIdx] != 0U) {
			ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
			Status = XKeyManager_DeleteKey(CompositeKeyIds[TypeIdx],
						XKEYMANAGER_ASU_SUBSYSTEM_ID);
			if (Status != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateErrorStatus(Status,
						XASUFW_KEYMANAGER_KEY_DELETE_ERROR);
				goto END;
			}
		}
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Store a pre-generated RSA key pair into the ASU internal vault.
 *
 * @param	KeyData		Pointer to the key data buffer.
 * @param	KeyLen		Length of the RSA key in bytes.
 * @param	VaultId		Identifier of the vault to store the key in.
 *
 * @return
 *	- XASUFW_SUCCESS, if key pair is stored successfully.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if input parameter is invalid.
 *	- XASUFW_KEYMANAGER_VAULT_NOT_FOUND, if the ASU vault does not exist.
 *	- XASUFW_KEYMANAGER_UPDATE_PVT_KEY_FAIL, if private key slot resolution or vault update
 *	  fails.
 *	- XASUFW_KEYMANAGER_UPDATE_PUB_KEY_FAIL, if public key slot resolution or vault update
 *	  fails.
 *
 *************************************************************************************************/
s32 XKeyManager_StoreRsaKeyPairInAsuVault(const u8 *KeyData, u32 KeyLen, u8 VaultId)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	CREATE_VOLATILE(DeleteStatus, XASUFW_FAILURE);
	u32 PvtKeyId = 0U;
	u32 PubKeyId = 0U;
	u16 PvtSlot = 0U;
	u16 PubSlot = 0U;
	XAsu_KeyManagerParams KmParams = {0};

	/** Validate input parameters. */
	if (KeyData == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	Status = XAsu_RsaValidateKeySize(KeyLen);
	if (Status != XASUFW_SUCCESS) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	if (VaultId != XKEYMANAGER_ASU_VAULT_ID) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	if (VaultManager.VaultInfo[VaultId].VaultBasePtr == NULL) {
		Status = XASUFW_KEYMANAGER_VAULT_NOT_FOUND;
		goto END;
	}

	/** Set up key manager parameters for vault storage. */
	KmParams.KeyMetadata.Length = (u16)KeyLen;
	KmParams.KeyMetadata.EpochTime = 0U;
	KmParams.KeyMetadata.UsageCount = XASU_KM_USAGE_COUNT_NON_DEPLETING_VALUE;
	KmParams.KeyMetadata.KeyUseCase = XKEYMANAGER_RSA_ALL_KEY_USE_CASES_VALUE;
	KmParams.KeyMetadata.CompositeKeyId = XASU_KM_COMPOSE_KEY_ID(VaultId, 0U, 0U);

	/** Resolve both slots before either is written. */
	Status = XKeyManager_GetKeySlot(VaultId, XASU_RSA_PVT_SUBVAULT_ID, 0U, &PvtSlot);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_PVT_KEY_FAIL);
		goto END;
	}
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetKeySlot(VaultId, XASU_RSA_PUB_SUBVAULT_ID, 0U, &PubSlot);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_PUB_KEY_FAIL);
		goto END;
	}

	/** Store the private key at its resolved slot. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_UpdateKeyVault(NULL, XASU_RSA_PVT_SUBVAULT_ID, &KmParams,
					    KeyData, PvtSlot, &PvtKeyId);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_PVT_KEY_FAIL);
		goto END;
	}

	/** Store the public key at its resolved slot. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_UpdateKeyVault(NULL, XASU_RSA_PUB_SUBVAULT_ID, &KmParams,
					    KeyData, PubSlot, &PubKeyId);
	if (Status != XASUFW_SUCCESS) {
		/* Status holds the cause from XKeyManager_UpdateKeyVault, retain it. */
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_PUB_KEY_FAIL);

		/* Attempt to clean up private key if public key update fails. */
		DeleteStatus = XKeyManager_DeleteKey(PvtKeyId, XKEYMANAGER_ASU_SUBSYSTEM_ID);
		if (DeleteStatus != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateBufStatus(Status, DeleteStatus);
		}
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function generates an ECC key pair for the wrapped-provisioning
 *		feature and stores it in the ASU-owned exportable key vault. The private key is
 *		restricted to the requested provisioning use case only, and neither
 *		half of the pair nor either key ID is returned to the caller: both halves stay in
 *		the vault and the unwrap path locates the private key internally. Each subsystem
 *		may hold one provisioning key pair per use case, so a request whose reserved slot is
 *		already populated is rejected instead of replacing the key: a repeated request
 *		cannot invalidate a public half which has already been handed out. Replacing a pair
 *		remains possible, but only as a deliberate act of the subsystem which owns it,
 *		which has to delete the pair first with XKeyManager_DeleteProvisioningKeyPair(). No
 *		other subsystem can do it on its behalf, because the slot is derived from the
 *		requesting subsystem rather than taken from the request.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	SubSystemId	Subsystem requesting the provisioning key pair. Together with the
 *				use case it selects the reserved key slot within the exportable
 *				vault.
 * @param	KeyUseCase	Provisioning use case the key pair is generated for, either the
 *				provisioning-material unwrap use case (ECIES) or the provisioning
 *				authenticated-encryption use case. It selects the reserved slot
 *				range and is stored as the private key's use case. Nothing else is
 *				caller-supplied: the vault id (ASU-owned exportable vault), curve
 *				(P-384), key length, epoch time and non-depleting usage count are
 *				all set internally.
 *
 * @return
 *	- XASUFW_SUCCESS, if the key pair is generated and both halves are stored.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if DmaPtr is NULL.
 *	- XASUFW_KEYMANAGER_GET_PROVISIONING_KEY_SLOT_FAILED, if no slot is reserved for the
 *		subsystem and use case, which is the case when the use case is not a supported
 *		provisioning use case or the subsystem is not assigned to any channel. The
 *		underlying cause is packed into the status. The key pair delete path reports a
 *		slot lookup failure with the same code.
 *	- XASUFW_KEYMANAGER_PROVISIONING_KEY_ALREADY_EXISTS, if the reserved slot already holds a
 *		provisioning private key for that use case, or the slot lookup did not confirm the
 *		slot is free.
 *	- Any other status comes through unchanged from XKeyManager_GenerateEccKeyPair(), which
 *		performs the generation and the vault store; see that function for the codes it
 *		returns. XASUFW_KEYMANAGER_KEY_SLOT_IN_USE arrives this way when the reserved slot
 *		is occupied, because the already-exists guard above inspects only the private half
 *		and a slot left holding a stranded public half reaches the store.
 *
 *************************************************************************************************/
s32 XKeyManager_GenerateProvisioningKeyPair(XAsufw_Dma *DmaPtr, u32 SubSystemId, u8 KeyUseCase)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	u32 PvtKeyId = 0U;
	u16 KeySlot = 0U;
	u32 KeyIds[XKEYMANAGER_KEY_PAIR_ID_COUNT] = {0U};
	XAsu_KeyManagerParams KmParams = {0};

	/** Validate input parameters. */
	if (DmaPtr == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/**
	 * Map the subsystem and the requested use case to their reserved slot in the exportable
	 * vault. Status holds the cause from the lookup, an unsupported use case or a subsystem
	 * with no channel, so it is retained rather than replaced.
	 */
	Status = XKeyManager_GetProvisioningKeySlot(SubSystemId, &KeySlot, KeyUseCase);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status,
				XASUFW_KEYMANAGER_GET_PROVISIONING_KEY_SLOT_FAILED);
		goto END;
	}

	/**
	 * A subsystem gets one provisioning key pair per use case. The slot is fixed for that
	 * pairing, so a populated slot means a key pair whose public half may already be held
	 * elsewhere: refuse, so that a repeated request cannot invalidate that copy by accident.
	 * This is not a guarantee that the pair cannot be replaced. The owning subsystem can
	 * delete it and generate a new one, which is a deliberate act of the party which handed
	 * the public half out, and no other subsystem can do it on its behalf.
	 * Only an explicit XASUFW_KEYMANAGER_KEY_NOT_FOUND lets the request through, so a lookup
	 * which is skipped or whose result is disturbed refuses the request instead of overwriting
	 * the key.
	 */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetProvisioningKeyId(KeySlot, &PvtKeyId, KeyUseCase);
	if (Status != XASUFW_KEYMANAGER_KEY_NOT_FOUND) {
		Status = XASUFW_KEYMANAGER_PROVISIONING_KEY_ALREADY_EXISTS;
		goto END;
	}

	/**
	 * The provisioning key pair profile is fixed and never taken from the caller: it is always
	 * generated on the NIST P-384 curve, stored only in the ASU-owned exportable vault, and
	 * restricted to the provisioning (ECIES) use cases, one per half. The private key is kept as a
	 * non-depleting key so it can service repeated unwrap requests. The slot is reserved per
	 * subsystem so the KeyId stays derivable after an export/import cycle. Populate the metadata
	 * internally so the caller cannot alter the profile.
	 */
	KmParams.KeyMetadata.CompositeKeyId = XASU_KM_COMPOSE_KEY_ID(
			XKEYMANAGER_ASU_EXPORTABLE_VAULT_ID, 0U, KeySlot);
	KmParams.KeyMetadata.KeyUseCase = KeyUseCase;
	KmParams.KeyMetadata.KeyAttributes = (u8)XASU_ECC_NIST_P384;
	KmParams.KeyMetadata.Length = (u16)XASU_ECC_P384_PVT_KEY_SIZE_IN_BYTES;
	KmParams.KeyMetadata.EpochTime = 0U;
	KmParams.KeyMetadata.UsageCount = XASU_KM_USAGE_COUNT_NON_DEPLETING_VALUE;
	/**
	 * The key pair goes to the vault, not to a caller buffer, so KeyObjectAddr stays zero.
	 * The vault path requires exactly one of KeyObjectAddr and KeyIdAddr to be set, so
	 * KeyIdAddr points at the local Key IDs; the assigned IDs are written through the KeyIds
	 * argument and never travel outside the ASU.
	 */
	KmParams.KeyObjectAddr = 0U;
	KmParams.KeyIdAddr = (u64)(UINTPTR)&KeyIds[0U];

	/**
	 * Generate and store the key pair through the common ECC key pair path, as the ASU: the
	 * exportable vault is ASU-owned, so its vault access check also rejects the case where an
	 * imported blob has handed vault 1 to another subsystem. Both halves land in the reserved
	 * slot of their sub-vault and the assigned Key IDs stay ASU-internal (not returned to the
	 * caller) so they cannot be reused as handles for other operations.
	 */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GenerateEccKeyPair(DmaPtr, &KmParams, KeyIds,
						XKEYMANAGER_ASU_SUBSYSTEM_ID);

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function deletes the wrapped-provisioning ECC key pair held in a
 *		subsystem's reserved slot of the ASU-owned exportable key vault, so that the
 *		subsystem can generate a fresh pair. Both halves are deleted as the ASU, because
 *		the exportable vault is ASU-owned and a client cannot delete from it directly.
 *		A slot holding only one half is accepted and cleaned up, so a pair whose public
 *		half was never stored does not keep the slot blocked. Each provisioning use case
 *		owns its own reserved slot, so only the pair held for the requested use case is
 *		deleted and the other use case's pair is left untouched.
 *
 * @param	SubSystemId	Subsystem whose provisioning key pair is deleted. Together with the
 *				use case it selects the reserved key slot within the exportable
 *				vault.
 * @param	KeyUseCase	Provisioning use case whose key pair is deleted, either the
 *				provisioning-material unwrap use case (ECIES) or the provisioning
 *				authenticated-encryption use case. It must be the use case the pair
 *				was generated for, because it selects the reserved slot range.
 *				Nothing else is caller-supplied: the vault id and the sub-vaults are
 *				fixed internally.
 *
 * @return
 *	- XASUFW_SUCCESS, if at least one half of the key pair is deleted.
 *	- XASUFW_KEYMANAGER_GET_PROVISIONING_KEY_SLOT_FAILED, if no slot is reserved for the
 *		subsystem and use case, which is the case when the use case is not a supported
 *		provisioning use case or the subsystem is not assigned to any channel. The
 *		underlying cause is packed into the status. The key pair generation path reports a
 *		slot lookup failure with the same code.
 *	- XASUFW_KEYMANAGER_KEY_NOT_FOUND, if the reserved slot held neither half, so there was no
 *		key pair to delete.
 *	- The delete failure reported by XKeyManager_DeleteKey() packed with
 *		XASUFW_KEYMANAGER_KEY_DELETE_ERROR, if deleting a half which is present fails. The
 *		cause, such as a missing vault, a vault no longer owned by the ASU or a failed
 *		zeroization, is kept in the first error field rather than discarded, so the value
 *		does not compare equal to XASUFW_KEYMANAGER_KEY_DELETE_ERROR on its own.
 *
 *************************************************************************************************/
s32 XKeyManager_DeleteProvisioningKeyPair(u32 SubSystemId, u8 KeyUseCase)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	static const XAsu_KeyManagerSubVaultType SubVaults[XKEYMANAGER_ASYM_KEY_TYPE_COUNT] = {
		XASU_ECC_PUB_SUBVAULT_ID, XASU_ECC_PVT_SUBVAULT_ID
	};
	u16 KeySlot = 0U;
	u32 KeyId = 0U;
	u32 TypeIdx = 0U;
	volatile u32 DeletedCount = 0U;

	/**
	 * Map the subsystem and the requested use case to their reserved slot in the exportable
	 * vault. The lookup failure is reported with the same code as the key pair generation path,
	 * so one cause does not reach the caller as two different codes depending on which command
	 * was issued.
	 */
	Status = XKeyManager_GetProvisioningKeySlot(SubSystemId, &KeySlot, KeyUseCase);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status,
				XASUFW_KEYMANAGER_GET_PROVISIONING_KEY_SLOT_FAILED);
		goto END;
	}

	/**
	 * Delete both halves from the reserved slot as the ASU, public half first. The private half
	 * is what XKeyManager_GetProvisioningKeyId() looks at, so it is the marker the key pair
	 * generation guard tests. Removing it last keeps that marker truthful: if
	 * the second delete fails, the pair is still usable and the generation guard still refuses
	 * cleanly, and re-issuing this operation clears the slot. Deleting it first would leave a
	 * public half that no path reports, yet which still occupies the reserved slot and makes the
	 * next generation fail inside the store.
	 * A half which is already absent is not an error: the goal is an empty slot, and stopping
	 * there would leave the other half behind and keep blocking a fresh key pair. Only an
	 * absent key is tolerated, not an unusable sub-vault: a vault 1 whose ECC public sub-vault
	 * has no capacity for the reserved slot, as an imported pre-public-half blob would give,
	 * is reported rather than silently half-deleted.
	 */
	for (TypeIdx = 0U; TypeIdx < XKEYMANAGER_ASYM_KEY_TYPE_COUNT; TypeIdx++) {
		KeyId = XASU_KM_COMPOSE_KEY_ID(XKEYMANAGER_ASU_EXPORTABLE_VAULT_ID,
						SubVaults[TypeIdx], KeySlot);

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyManager_DeleteKey(KeyId, XKEYMANAGER_ASU_SUBSYSTEM_ID);
		if (Status == XASUFW_SUCCESS) {
			DeletedCount++;
		} else if (Status != XASUFW_KEYMANAGER_KEY_NOT_FOUND) {
			/* Status holds the cause from XKeyManager_DeleteKey, retain it. */
			Status = XAsufw_UpdateErrorStatus(Status,
					XASUFW_KEYMANAGER_KEY_DELETE_ERROR);
			goto END;
		} else {
			/* This sub-vault holds nothing for the subsystem, continue. */
		}
	}

	/** Report an empty slot as key not found: there was no key pair to delete. */
	if (DeletedCount == 0U) {
		Status = XASUFW_KEYMANAGER_KEY_NOT_FOUND;
	} else {
		Status = XASUFW_SUCCESS;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Map a subsystem and a provisioning use case to the ECC key slot reserved for that
 *		pairing in the ASU-owned exportable vault. Each use case owns a disjoint range of
 *		XASU_MAX_CHANNELS_SUPPORTED slots and the slot within a range is the subsystem's
 *		channel index plus one, so the unwrap use case occupies slots
 *		1..XASU_MAX_CHANNELS_SUPPORTED and the authenticated-encryption use case occupies
 *		the range above it. A subsystem can therefore hold one key pair per use case
 *		without the two ever resolving to the same slot.
 *
 * @param	SubSystemId	Subsystem whose reserved slot is requested.
 * @param	SlotPtr		Pointer that receives the 1-based slot on success.
 * @param	KeyUseCase	Provisioning use case the slot is requested for. Selects the range.
 *
 * @return
 *	- XASUFW_SUCCESS, if the use case is supported and the subsystem maps to a channel.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if SlotPtr is NULL or the subsystem is not assigned to
 *		any channel.
 *	- XASUFW_KEYMANAGER_INVALID_PROVISIONING_USE_CASE, if the use case is not exactly one of
 *		the supported provisioning use cases.
 *
 *************************************************************************************************/
static s32 XKeyManager_GetProvisioningKeySlot(u32 SubSystemId, u16 *SlotPtr, u8 KeyUseCase)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	volatile u32 Index = 0U;
	u16 SlotBase = 0U;

	if (SlotPtr == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/**
	 * Select the reserved range for the use case. The comparison is an exact match rather than
	 * a bit test, so a value carrying more than one use case is refused: a provisioning key
	 * pair holds exactly one. An unrecognised use case is refused rather than defaulted to a
	 * range, so a caller can never land on the slot of another use case.
	 */
	if (KeyUseCase == XASU_KEYMANAGER_ECC_PVT_PROV_UNWRAP_USE_CASE) {
		SlotBase = 0U;
	} else if (KeyUseCase == XASU_KEYMANAGER_ECC_PVT_KEY_AUTH_ENC_USE_CASE) {
		SlotBase = (u16)XASU_MAX_CHANNELS_SUPPORTED;
	} else {
		Status = XASUFW_KEYMANAGER_INVALID_PROVISIONING_USE_CASE;
		goto END;
	}

	for (Index = 0U; Index < XASU_MAX_CHANNELS_SUPPORTED; Index++) {
		if (SubSystemId == XAsu_GetSubsysIdFromIpiMask(XAsu_GetIpiMask(Index))) {
			*SlotPtr = (u16)(Index + XKEYMANAGER_KEY_INDEX_OFFSET + SlotBase);
			Status = XASUFW_SUCCESS;
			break;
		}
	}

	/** The subsystem holds no channel, so no slot is reserved for it. */
	if (Index == XASU_MAX_CHANNELS_SUPPORTED) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Derive the provisioning private key ID for a reserved slot in the ASU-owned
 *		exportable vault and confirm the slot is occupied by a key that carries the
 *		requested provisioning use case. Lets the key pair generation guard test the slot
 *		without the caller ever holding the KeyId. Because the ID is derived rather than
 *		remembered, it also resolves after the vault has been exported and imported again.
 *		The caller resolves the slot first with XKeyManager_GetProvisioningKeySlot(), so the
 *		mapping is not repeated here.
 *
 * @param	KeySlot		Reserved slot of the subsystem whose private key ID is requested.
 * @param	KeyIdPtr	Pointer that receives the private key ID on success.
 * @param	KeyUseCase	Provisioning use case the slot must carry. Must be the same use case
 *				the slot was resolved for, so the guard tests the key pair which
 *				would actually be replaced.
 *
 * @return
 *	- XASUFW_SUCCESS, if the slot holds a key carrying the requested use case.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if KeyIdPtr is NULL.
 *	- XASUFW_KEYMANAGER_KEY_NOT_FOUND, if the vault or the slot cannot be resolved, or the slot
 *	  does not carry that use case. Reported only from the branch which observed the slot to
 *	  be empty, because it is the value the key pair generation guard treats as permissive.
 *	- XASUFW_FAILURE, if the lookup did not run to a decision.
 *
 *************************************************************************************************/
static s32 XKeyManager_GetProvisioningKeyId(u16 KeySlot, u32 *KeyIdPtr, u8 KeyUseCase)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	u32 KeyId = 0U;

	if (KeyIdPtr == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	KeyId = XASU_KM_COMPOSE_KEY_ID(XKEYMANAGER_ASU_EXPORTABLE_VAULT_ID,
					XASU_ECC_PVT_SUBVAULT_ID, KeySlot);

	/**
	 * Validate the slot without consuming a use of the key: the caller fetches the key object
	 * itself when it is actually used.
	 * XASUFW_KEYMANAGER_KEY_NOT_FOUND is the one value which lets the key pair generation
	 * guard replace the slot contents, so it is reported only from the branch which observed
	 * the slot to be empty. It is deliberately not the initial value: a lookup whose result is
	 * disturbed leaves the initial failure and the guard refuses.
	 */
	if (XKeyManager_GetKeyObjectPtr(KeyId, XKEYMANAGER_ASU_SUBSYSTEM_ID, KeyUseCase,
			(u8)FALSE) != NULL) {
		*KeyIdPtr = KeyId;
		Status = XASUFW_SUCCESS;
	} else {
		Status = XASUFW_KEYMANAGER_KEY_NOT_FOUND;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Store a single key in the requested sub-vault of an ASU key vault.
 *
 * @param	ParamsPtr	Pointer to key manager parameters containing the key metadata and
 *				the key data address.
 * @param	KeyIdPtr	Pointer that is updated with the composite key ID of the stored key.
 *
 * @return
 *	- XASUFW_SUCCESS, if the key is stored successfully.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if an input parameter is invalid, or the requested key
 *	  slot exceeds the sub-vault capacity.
 *	- XASUFW_KEYMANAGER_VAULT_NOT_FOUND, if the vault is not initialized.
 *	- XASUFW_KEYMANAGER_KEY_SLOT_IN_USE, if the requested key slot is already occupied,
 *	  packed with the operation-specific slot resolution error.
 *	- XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED, if the sub-vault has no free slot.
 *	- XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL, if the key slot cannot be resolved.
 *
 *************************************************************************************************/
s32 XKeyManager_StoreKeyInAsuVault(const XAsu_KeyManagerParams *ParamsPtr, u32 *KeyIdPtr)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	XAsu_KeyManagerSubVaultType KeyType;
	const u8 *KeyData;
	u16 ResolvedSlot = 0U;
	u8 VaultId;

	/** Validate input parameters. */
	if ((ParamsPtr == NULL) || (KeyIdPtr == NULL)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	VaultId = XASU_KM_GET_VAULT_ID(ParamsPtr->KeyMetadata.CompositeKeyId);
	if (VaultId != XKEYMANAGER_ASU_VAULT_ID) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Mask out the wrapped-key bit to obtain the target sub-vault identifier. */
	KeyType = (XAsu_KeyManagerSubVaultType)(
			XASU_KM_GET_KEY_TYPE(ParamsPtr->KeyMetadata.CompositeKeyId) &
			~XASU_KM_KEYTYPE_WRAPPED_BIT_MASK);
	KeyData = (const u8 *)(UINTPTR)ParamsPtr->KeyObjectAddr;

	/** Validate key data and key type. */
	if ((KeyData == NULL) || (KeyType >= XKEYMANAGER_MAX_SUB_VAULTS)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Validate the vault is initialized. */
	if (VaultManager.VaultInfo[VaultId].VaultBasePtr == NULL) {
		Status = XASUFW_KEYMANAGER_VAULT_NOT_FOUND;
		goto END;
	}

	/** Resolve the target slot (requested or first free) before storing. */
	Status = XKeyManager_GetKeySlot(VaultId, KeyType,
			XASU_KM_GET_KEY_INDEX(ParamsPtr->KeyMetadata.CompositeKeyId),
			&ResolvedSlot);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
		goto END;
	}

	/** Store the key in the requested sub-vault at the resolved slot. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_UpdateKeyVault(NULL, KeyType, ParamsPtr, KeyData, ResolvedSlot,
			KeyIdPtr);

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Check the declared length of a caller-supplied PQC key against the length its
 *		parameter set defines for the sub-vault it is being stored in.
 *
 * @param	KeyType		Sub-vault the key is being stored in.
 * @param	ParamsPtr	Pointer to the XAsu_KeyManagerParams.
 *
 * @return
 *	- XASUFW_SUCCESS, if the sub-vault is not a PQC one, or the declared length matches.
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if the PQC parameter set in KeyAttributes is unsupported.
 *	- XASUFW_KEYMANAGER_INVALID_BUF_SIZE, if the declared length disagrees with the parameter
 *	  set.
 *
 * @note	Only the store path may apply this check. The key data it stores is the caller's
 *		buffer, which the handler validated against the declared length, so copying the
 *		parameter set length out of it would read past the validated window unless the two
 *		agree. A key generated into the vault is written from an internal buffer that the
 *		declared length does not describe, and a key pair is written by two calls that a
 *		single declared length cannot satisfy at once.
 *
 *************************************************************************************************/
static s32 XKeyManager_ValidatePqcStoreKeyLength(XAsu_KeyManagerSubVaultType KeyType,
				const XAsu_KeyManagerParams *ParamsPtr)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	u32 PubKeyLen = 0U;
	u32 PrivKeyLen = 0U;
	u32 ExpectedLength;

	if ((KeyType == XASU_MLDSA_PVT_SUBVAULT_ID) || (KeyType == XASU_MLDSA_PUB_SUBVAULT_ID)) {
		Status = XAsu_KmGetMldsaKeyLengths(ParamsPtr->KeyMetadata.KeyAttributes,
						&PubKeyLen, &PrivKeyLen);
	} else if ((KeyType == XASU_MLKEM_PVT_SUBVAULT_ID) ||
		   (KeyType == XASU_MLKEM_PUB_SUBVAULT_ID)) {
		Status = XAsu_KmGetMlkemKeyLengths(ParamsPtr->KeyMetadata.KeyAttributes,
						&PubKeyLen, &PrivKeyLen);
	} else {
		Status = XASUFW_SUCCESS;
		goto END;
	}

	if (Status != XASUFW_SUCCESS) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	if ((KeyType == XASU_MLDSA_PVT_SUBVAULT_ID) || (KeyType == XASU_MLKEM_PVT_SUBVAULT_ID)) {
		ExpectedLength = PrivKeyLen;
	} else {
		ExpectedLength = PubKeyLen;
	}

	if ((u32)ParamsPtr->KeyMetadata.Length != ExpectedLength) {
		Status = XASUFW_KEYMANAGER_INVALID_BUF_SIZE;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Write the provided key into the vault at a slot the caller already resolved
 *		through XKeyManager_GetKeySlot. This function only writes; it never resolves.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	KeyType		Sub-vault that contains the key.
 * @param	ParamsPtr	Pointer to the XAsu_KeyManagerParams.
 * @param	KeyData		Pointer to the key data.
 * @param	ResolvedSlot	Already-resolved 1-based slot to write the key to.
 * @param	KeyIdPtr	Pointer to the output composite Key ID.
 *
 * @return
 * 	- XASUFW_SUCCESS, if key vault updation is successful.
 * 	- XASUFW_FAILURE, if key vault updation fails, including an invalid (zero) ResolvedSlot.
 * 	- XASUFW_KEYMANAGER_INVALID_PARAM, if the PQC parameter set in KeyAttributes is unsupported.
 * 	- XASUFW_KEYMANAGER_INVALID_BUF_SIZE, if the key length to store is zero or exceeds the
 * 	  sub-vault's maximum key size.
 *	- XASUFW_DMA_COPY_FAIL, if the DMA transfer or the memory copy fails.
 *
 *************************************************************************************************/
static s32 XKeyManager_UpdateKeyVault(XAsufw_Dma *DmaPtr, XAsu_KeyManagerSubVaultType KeyType,
			const XAsu_KeyManagerParams *ParamsPtr, const u8 *KeyData, u16 ResolvedSlot,
			u32 *KeyIdPtr)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	u32 SubVaultOffset;
	void* SubVaultBasePtr;
	XKeyManager* KeyVaultPtr;
	XAsu_KeyManagerKeyMetadata *KeyMetadataPtr;
	void* KeyContentPtr;
	u32 KeyObjectSize = 0U;
	u32 MaxKeySize = 0U;
	u32 KeyCopyLength = 0U;
	u32 PqcPubKeyLen = 0U;
	u32 PqcPrivKeyLen = 0U;
	u16 MetadataLength = ParamsPtr->KeyMetadata.Length;
	u8 VaultId = XASU_KM_GET_VAULT_ID(ParamsPtr->KeyMetadata.CompositeKeyId);

	/** Fail safe on an unresolved (zero) slot: guards the pointer math below from underflow. */
	if (ResolvedSlot == 0U) {
		goto END;
	}

	/** Get vault pointer and sub-vault offset. */
	KeyVaultPtr = (XKeyManager *)VaultManager.VaultInfo[VaultId].VaultBasePtr;
	SubVaultOffset = KeyVaultPtr->SubVaultHeaders[KeyType].Offset;

	/** Calculate sub-vault base address. */
	SubVaultBasePtr = (u8 *)KeyVaultPtr + SubVaultOffset;

	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	KeyCopyLength = ParamsPtr->KeyMetadata.Length;
	/* Determine maximum key size based on key type. */
	if (KeyType == XASU_AES_SUBVAULT_ID) {
		MaxKeySize = XASU_AES_KEY_SIZE_256BIT_IN_BYTES;
	} else if (KeyType == XASU_IV_SUBVAULT_ID) {
		MaxKeySize = XASU_AES_IV_SIZE_128BIT_IN_BYTES;
	} else if (KeyType == XASU_KDF_HMAC_SUBVAULT_ID) {
		MaxKeySize = XASU_KM_KDF_HMAC_MAX_KEY_LENGTH;
	} else if (KeyType == XASU_RSA_PVT_SUBVAULT_ID) {
		MaxKeySize = XRSA_MAX_KEY_OBJ_SIZE_IN_BYTES;
		KeyCopyLength = XRSA_MAX_KEY_OBJ_SIZE_IN_BYTES;
	} else if (KeyType == XASU_RSA_PUB_SUBVAULT_ID) {
		MaxKeySize = XRSA_MAX_KEY_WITH_PUBEXP_SIZE_IN_BYTES;
		KeyCopyLength += XRSA_PUBEXP_SIZE_IN_BYTES;
	} else if (KeyType == XASU_ECC_PVT_SUBVAULT_ID) {
		MaxKeySize = XASU_ECC_P521_PVT_KEY_SIZE_IN_BYTES;
	} else if (KeyType == XASU_ECC_PUB_SUBVAULT_ID) {
		MaxKeySize = XASU_ECC_P521_PUB_KEY_SIZE_IN_BYTES;
		KeyCopyLength = XAsu_DoubleCurveLength(ParamsPtr->KeyMetadata.Length);
	} else if (KeyType == XASU_X509_SUBVAULT_ID) {
		MaxKeySize = XASU_X509_MAX_SIZE_IN_BYTES;
	} else if (KeyType == XASU_LMS_SUBVAULT_ID) {
		MaxKeySize = XASU_LMS_MAX_PUB_KEY_SIZE;
	} else if ((KeyType == XASU_MLDSA_PVT_SUBVAULT_ID) ||
		   (KeyType == XASU_MLDSA_PUB_SUBVAULT_ID)) {
		/*
		 * The ML-DSA public key and private key have unrelated sizes, so a single
		 * declared length cannot describe both. Both lengths come from the ML-DSA
		 * parameter set in KeyAttributes, and the sub-vault being written decides which
		 * one applies: XASU_MLDSA_PUB_SUBVAULT_ID stores the public key and
		 * XASU_MLDSA_PVT_SUBVAULT_ID stores the private key.
		 *
		 * Each object therefore records the length of the key it holds. The vault
		 * resolver hands that length to the core as KeyLen, and the core rejects a key
		 * shorter than the ML-DSA parameter set requires for that key.
		 */
		Status = XAsu_KmGetMldsaKeyLengths(ParamsPtr->KeyMetadata.KeyAttributes,
						&PqcPubKeyLen, &PqcPrivKeyLen);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}

		if (KeyType == XASU_MLDSA_PVT_SUBVAULT_ID) {
			MaxKeySize = XASU_MLDSA_MAX_PRIV_KEY_LEN;
			KeyCopyLength = PqcPrivKeyLen;
		} else {
			MaxKeySize = XASU_MLDSA_MAX_PUB_KEY_LEN;
			KeyCopyLength = PqcPubKeyLen;
		}
		MetadataLength = (u16)KeyCopyLength;
	} else if ((KeyType == XASU_MLKEM_PVT_SUBVAULT_ID) ||
		   (KeyType == XASU_MLKEM_PUB_SUBVAULT_ID)) {
		/*
		 * The ML-KEM encapsulation key and decapsulation key have unrelated sizes, so a
		 * single declared length cannot describe both. Both lengths come from the ML-KEM
		 * parameter set in KeyAttributes, and the sub-vault being written decides which
		 * one applies: XASU_MLKEM_PUB_SUBVAULT_ID stores the encapsulation key and
		 * XASU_MLKEM_PVT_SUBVAULT_ID stores the decapsulation key.
		 *
		 * Each object therefore records the length of the key it holds. The vault
		 * resolver hands that length to the core as KeyLen, and the core rejects a key
		 * shorter than the ML-KEM parameter set requires for that key.
		 */
		Status = XAsu_KmGetMlkemKeyLengths(ParamsPtr->KeyMetadata.KeyAttributes,
						&PqcPubKeyLen, &PqcPrivKeyLen);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}

		if (KeyType == XASU_MLKEM_PVT_SUBVAULT_ID) {
			MaxKeySize = XASU_MLKEM_MAX_PRIV_KEY_LEN;
			KeyCopyLength = PqcPrivKeyLen;
		} else {
			MaxKeySize = XASU_MLKEM_MAX_PUB_KEY_LEN;
			KeyCopyLength = PqcPubKeyLen;
		}
		MetadataLength = (u16)KeyCopyLength;
	} else {
		/* Do nothing */
	}

	/**
	 * Validate key copy length against maximum key size. A zero length is rejected as well,
	 * so that an unhandled key type, which leaves both values at zero, cannot silently store
	 * an empty key.
	 */
	if ((KeyCopyLength == 0U) || (KeyCopyLength > MaxKeySize)) {
		Status = XASUFW_KEYMANAGER_INVALID_BUF_SIZE;
		goto END;
	}

	/** Get key object size based on key type. */
	KeyObjectSize = XKeyManager_KeyObjectSizeLookup[KeyType];

	/** Calculate pointer to key metadata within sub-vault. */
	KeyMetadataPtr = (XAsu_KeyManagerKeyMetadata *)((u8 *)SubVaultBasePtr +
			(KeyObjectSize * ((u32)ResolvedSlot - XKEYMANAGER_KEY_INDEX_OFFSET)));

	/** Calculate pointer to key content area. */
	KeyContentPtr = (u8 *)KeyMetadataPtr + sizeof(XAsu_KeyManagerKeyMetadata);

	/** Copy key data to vault using DMA. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	if (DmaPtr != NULL) {
		Status = XAsufw_DmaXfr(DmaPtr, (u64)(UINTPTR)KeyData, (u64)(UINTPTR)KeyContentPtr,
				       KeyCopyLength, 0U);
	} else {
		Status = Xil_SMemCpy((u8 *)KeyContentPtr, MaxKeySize, KeyData, KeyCopyLength,
				     KeyCopyLength);
	}
	if (Status != XASUFW_SUCCESS) {
		Status = XASUFW_DMA_COPY_FAIL;
		goto END;
	}

	/** Populate key metadata. The stored composite ID is what the caller is handed back. */
	KeyMetadataPtr->CompositeKeyId = XASU_KM_COMPOSE_KEY_ID(VaultId, KeyType, ResolvedSlot);
	KeyMetadataPtr->EpochTime = ParamsPtr->KeyMetadata.EpochTime;
	KeyMetadataPtr->UsageCount = ParamsPtr->KeyMetadata.UsageCount;
	KeyMetadataPtr->Length = MetadataLength;
	KeyMetadataPtr->KeyUseCase = ParamsPtr->KeyMetadata.KeyUseCase;
	KeyMetadataPtr->KeyAttributes = ParamsPtr->KeyMetadata.KeyAttributes;

	/** Increment active keys counter in sub-vault header. */
	KeyVaultPtr->SubVaultHeaders[KeyType].ActiveKeys++;

	*KeyIdPtr = KeyMetadataPtr->CompositeKeyId;

	/** Mark key vault as dirty if it is not the ASU vault. */
	if (VaultId != XKEYMANAGER_ASU_VAULT_ID) {
		IsKeyVaultDirty = XKEYMANAGER_VAULT_DIRTY_VALUE;
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Reserve a registry entry for a new vault, at the requested ID or at the first
 *		free one, and record the owning subsystem.
 *
 * @param	SubSystemId	Subsystem that will own the vault.
 * @param	ReqVaultId	Requested vault ID, or 0 to auto-assign the first free ID.
 * @param	VaultIdPtr	Updated with the reserved vault ID on success.
 *
 * @return
 * 	- XASUFW_SUCCESS, if vault information is updated successfully.
 * 	- XASUFW_KEYMANAGER_INVALID_PARAM, if the requested vault ID is out of range.
 * 	- XASUFW_KEYMANAGER_VAULT_ID_IN_USE, if the requested vault ID is already occupied.
 * 	- XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED, if no space is available for a new vault.
 *
 *************************************************************************************************/
static s32 XKeyManager_UpdateVaultInfo(u32 SubSystemId, u8 ReqVaultId, u8 *VaultIdPtr)
{
	CREATE_VOLATILE(Status, XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED);
	u8 Index = 0U;

	/** Validate the requested vault ID before it is used to index the vault registry. */
	if (ReqVaultId >= XASU_KM_MAX_VAULTS) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Claim the requested vault ID, rejecting it if another vault already holds it. */
	if (ReqVaultId != 0U) {
		if (VaultManager.VaultInfo[ReqVaultId].VaultSize != 0U) {
			Status = XASUFW_KEYMANAGER_VAULT_ID_IN_USE;
		} else {
			VaultManager.VaultInfo[ReqVaultId].SubSystemId = SubSystemId;
			*VaultIdPtr = ReqVaultId;
			Status = XASUFW_SUCCESS;
		}
		goto END;
	}

	/** With no ID requested, scan the registry and claim the first free entry. */
	for (Index = 0U; Index < XASU_KM_MAX_VAULTS; Index++) {
		if (VaultManager.VaultInfo[Index].VaultSize == 0U) {
			VaultManager.VaultInfo[Index].SubSystemId = SubSystemId;
			*VaultIdPtr = Index;
			Status = XASUFW_SUCCESS;
			break;
		}
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Validate key access rights and usage permissions for a given key.
 *
 * @param	SubSystemId	Subsystem identifier requesting key access.
 * @param	SubVaultPtr	Pointer to the sub-vault containing the key.
 * @param	KeyUseCase	Bit mask of the use cases requested for the key. The key must hold
 * 				every requested use case, so passing more than one bit narrows the
 * 				set of keys that qualify. A zero mask is not a valid request.
 * @param	VaultId		Identifier of the vault containing the key.
 * @param	IsKeyUsed	TRUE if the key is being used, FALSE if only validated.
 *
 * @return
 * 	- XASUFW_SUCCESS, if key is valid and accessible for every requested use case.
 * 	- XASUFW_KEYMANAGER_INVALID_PARAM, if an input parameter is invalid.
 * 	- XASUFW_KEYMANAGER_ACCESS_DENIED, if subsystem lacks access rights.
 * 	- XASUFW_KEYMANAGER_KEY_EXPIRED, if key usage count is exhausted or the current epoch time has
 * 		reached or passed the key's epoch time.
 * 	- XASUFW_KEYMANAGER_KEY_USE_CASE_ERROR, if KeyUseCase is zero or the key does not hold
 * 		all the requested use cases.
 *
 *************************************************************************************************/
static s32 XKeyManager_CheckKeyValidity(u32 SubSystemId, u8 *SubVaultPtr, u8 KeyUseCase, u8 VaultId,
					u8 IsKeyUsed)
{
	s32 Status = XASUFW_FAILURE;
	u8 Index = 0U;
	XAsu_KeyManagerKeyMetadata *MetaDataPtr = (XAsu_KeyManagerKeyMetadata *)SubVaultPtr;
	u16 AllowedAccessRights = 0U;
	XKeyManager *KeyVaultPtr = (XKeyManager *)VaultManager.VaultInfo[VaultId].VaultBasePtr;
	u8 KeyType = XASU_KM_GET_KEY_TYPE(MetaDataPtr->CompositeKeyId);

	AllowedAccessRights = KeyVaultPtr->Header.AccessRights;

	if (SubSystemId == XKEYMANAGER_ASU_SUBSYSTEM_ID) {
		if (AllowedAccessRights != 0U) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}
	} else {
		if ((!XASU_IS_REDUNDANT_BYTE_VALID(AllowedAccessRights))) {
			Status = XASUFW_KEYMANAGER_INVALID_PARAM;
			goto END;
		}
	}

	/** Check for access rights. */
	if (VaultManager.VaultInfo[VaultId].SubSystemId != SubSystemId) {
		for (Index = 0U; Index < XASU_MAX_CHANNELS_SUPPORTED; Index++) {
			if (XKEYMANAGER_IS_BIT_SET(AllowedAccessRights, Index)) {
				if (SubSystemId == XAsu_GetSubsysIdFromIpiMask(XAsu_GetIpiMask(Index))) {
					break;
				}
			}
		}
		if (Index == XASU_MAX_CHANNELS_SUPPORTED) {
			Status = XASUFW_KEYMANAGER_ACCESS_DENIED;
			goto END;
		}
	}

	/** Reject the key unless it holds every requested use case. */
	if ((KeyUseCase == 0U) || ((MetaDataPtr->KeyUseCase & KeyUseCase) != KeyUseCase)) {
		Status = XASUFW_KEYMANAGER_KEY_USE_CASE_ERROR;
		goto END;
	}

	/** If the key is being used, enforce epoch-time expiry and usage-count expiry. */
	if (IsKeyUsed != FALSE) {
		/** Check if the key is expired based on the epoch time. */
		if (MetaDataPtr->EpochTime != 0U) {
			if (MetaDataPtr->EpochTime <= CurrentEpochTime) {
				Status = XASUFW_KEYMANAGER_KEY_EXPIRED;
				goto END;
			}
		}

		/** Decrement usage count if applicable. */
		if (MetaDataPtr->UsageCount != XASU_KM_USAGE_COUNT_NON_DEPLETING_VALUE) {
			if (MetaDataPtr->UsageCount == 0U) {
				Status = XASUFW_KEYMANAGER_KEY_EXPIRED;
				goto END;
			}
			MetaDataPtr->UsageCount -= XKEYMANAGER_USAGE_COUNT_DEC_VALUE;

			/** If usage count reaches zero, update counters (key transitions to deactivated). */
			if (MetaDataPtr->UsageCount == 0U) {
				KeyVaultPtr->SubVaultHeaders[KeyType].ActiveKeys--;
				KeyVaultPtr->SubVaultHeaders[KeyType].DeactivatedKeys++;
			}
		}
	}

	Status = XASUFW_SUCCESS;

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function translates the X.509 key usage extension of a certificate into the
 *		key vault use case which the ECC public key of that certificate is granted.
 *
 * @param	KeyUsage	Bit wise OR of the XASU_X509_KEY_USAGE_* masks.
 *
 * @return
 *	- Bit wise OR of the XASU_KEYMANAGER_ECC_PUB_* use case masks.
 *
 *************************************************************************************************/
u8 XKeyManager_GetEccPubKeyUseCase(u32 KeyUsage)
{
	u8 KeyUseCase = 0U;

	/**
	 * The two encodings are unrelated bitmasks, so each X.509 key usage bit is mapped
	 * explicitly.
	 */
	if ((KeyUsage & (XASU_X509_KEY_USAGE_DIGITAL_SIGNATURE |
			 XASU_X509_KEY_USAGE_NON_REPUDIATION |
			 XASU_X509_KEY_USAGE_KEY_CERT_SIGN |
			 XASU_X509_KEY_USAGE_CRL_SIGN)) != 0U) {
		KeyUseCase |= (u8)XASU_KEYMANAGER_ECC_PUB_SIGN_VER_USE_CASE;
	}

	if ((KeyUsage & XASU_X509_KEY_USAGE_KEY_AGREEMENT) != 0U) {
		KeyUseCase |= (u8)XASU_KEYMANAGER_ECC_PUB_KEY_AGREEMENT_USE_CASE;
	}

	if ((KeyUsage & XASU_X509_KEY_USAGE_DATA_ENCIPHERMENT) != 0U) {
		KeyUseCase |= (u8)XASU_KEYMANAGER_ECC_PUB_KEY_AUTH_ENC_USE_CASE;
	}

	return KeyUseCase;
}

/*************************************************************************************************/
/**
 * @brief	Map the certificate's public key type to the sub-vault that holds its raw key.
 *
 * @param	CertInfo	Pointer to the parsed X.509 certificate information.
 * @param	SubVaultTypePtr	Updated with the raw public key sub-vault on success.
 *
 * @return
 *	- XASUFW_SUCCESS, if the certificate public key type is supported.
 *	- XASUFW_KEYMANAGER_INVALID_KEY_TYPE, if it is not.
 *
 *************************************************************************************************/
static s32 XKeyManager_GetX509RawKeySubVault(const X509_CertInfo *CertInfo,
				XAsu_KeyManagerSubVaultType *SubVaultTypePtr)
{
	s32 Status = XASUFW_KEYMANAGER_INVALID_KEY_TYPE;

	if (CertInfo->PublicKeyType == X509_PUB_KEY_ECC) {
		*SubVaultTypePtr = XASU_ECC_PUB_SUBVAULT_ID;
		Status = XASUFW_SUCCESS;
	} else if (CertInfo->PublicKeyType == X509_PUB_KEY_RSA) {
		*SubVaultTypePtr = XASU_RSA_PUB_SUBVAULT_ID;
		Status = XASUFW_SUCCESS;
	} else {
		/* Unsupported public key type. */
	}

	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Store a raw public key extracted from X.509 certificate to the key vault.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	KeyParams	Pointer to key manager parameters containing vault
 *				information for storing the raw key.
 * @param	CertInfo	Pointer to the parsed X.509 certificate information.
 * @param	RawKeySubVaultType	Sub-vault holding the raw key, resolved by the caller.
 * @param	RawSlot		Already-resolved slot to write the raw key to.
 * @param	RawKeyIdPtr	Pointer to store the generated raw key ID.
 *
 * @return
 *	- XASUFW_SUCCESS, if raw public key is stored successfully.
 *	- XASUFW_FAILURE, in case of failure.
 *	- XASUFW_MEM_COPY_FAIL, if memory copy operation fails.
 *	- XASUFW_KEYMANAGER_INVALID_EXPONENT_SIZE, if the public exponent size is not supported.
 *	- XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL, if the vault update fails.
 *
 *************************************************************************************************/
static s32 XKeyManager_StoreX509RawPublicKey(XAsufw_Dma *DmaPtr,
					     const XAsu_KeyManagerParams *KeyParams,
					     const X509_CertInfo *CertInfo,
					     XAsu_KeyManagerSubVaultType RawKeySubVaultType,
					     u16 RawSlot, u32 *RawKeyIdPtr)
{
	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	XAsu_KeyManagerParams RawKeyParams = {0};
	u32 KeyLen;
	u8 *KeyData;
	u8 KeyUseCase = 0U;
	u8 KeyAttributes = 0U;
	u8 VaultId = XASU_KM_GET_VAULT_ID(KeyParams->KeyMetadata.CompositeKeyId);

	/** Select the key data based on the sub-vault type resolved by the caller. */
	if (RawKeySubVaultType == XASU_ECC_PUB_SUBVAULT_ID) {
		/** Skip one byte indicating compression type. */
		KeyLen = CertInfo->PublicKey.EccPublicKey.PublicKeyLen - XASUFW_VALUE_ONE;

		/*
		 * For ECC public type, key manager is internally doubling the size so divide
		 * the key size by two.
		 */
		KeyLen = KeyLen / XASUFW_VALUE_TWO;

		KeyData = CertInfo->PublicKey.EccPublicKey.PublicKey + XASUFW_BUFFER_INDEX_ONE;

		/**
		 * Record the NIST curve type (from the coordinate length) in the key attributes;
		 * the vault validates it against the requested curve type on use.
		 */
		switch (KeyLen) {
		case XASU_ECC_P192_PVT_KEY_SIZE_IN_BYTES:
			KeyAttributes = (u8)XASU_ECC_NIST_P192;
			break;
		case XASU_ECC_P224_PVT_KEY_SIZE_IN_BYTES:
			KeyAttributes = (u8)XASU_ECC_NIST_P224;
			break;
		case XASU_ECC_P256_PVT_KEY_SIZE_IN_BYTES:
			KeyAttributes = (u8)XASU_ECC_NIST_P256;
			break;
		case XASU_ECC_P384_PVT_KEY_SIZE_IN_BYTES:
			KeyAttributes = (u8)XASU_ECC_NIST_P384;
			break;
		case XASU_ECC_P521_PVT_KEY_SIZE_IN_BYTES:
			KeyAttributes = (u8)XASU_ECC_NIST_P521;
			break;
		default:
			Status = XASUFW_KEYMANAGER_INVALID_KEY_TYPE;
			goto END;
		}

		/** Map X.509 key usage to ECC public key usage. */
		KeyUseCase = XKeyManager_GetEccPubKeyUseCase(CertInfo->KeyUsage);
	} else if (RawKeySubVaultType == XASU_RSA_PUB_SUBVAULT_ID) {
		KeyLen = CertInfo->PublicKey.RsaPublicKey.ModulusLen;

		/**
		 * The RSA public key vault object stores the public exponent immediately followed
		 * by the modulus (PubExp || Modulus), and XKeyManager_UpdateKeyVault() copies
		 * (Length + XRSA_PUBEXP_SIZE_IN_BYTES) bytes for RSA public keys. Pack the
		 * certificate's exponent and modulus into a scratch buffer in that layout.
		 */
		KeyData = (u8 *)(UINTPTR)XASUFW_CRYPTO_AUX_BUF_ADDR;

		/**
		 * Map X.509 key usage to RSA public key usage:
		 * - digitalSignature/nonRepudiation -> SIGN_VER
		 * - keyEncipherment/dataEncipherment -> ENCRYPT
		 * - keyAgreement -> KEY_TRANSPORT
		 */
		if ((CertInfo->KeyUsage & (XASU_X509_KEY_USAGE_DIGITAL_SIGNATURE |
					   XASU_X509_KEY_USAGE_NON_REPUDIATION)) != 0U) {
			KeyUseCase |= XASU_KEYMANAGER_RSA_PUB_SIGN_VER_USE_CASE;
		}

		if ((CertInfo->KeyUsage & (XASU_X509_KEY_USAGE_KEY_ENCIPHERMENT |
					   XASU_X509_KEY_USAGE_DATA_ENCIPHERMENT)) != 0U) {
			KeyUseCase |= XASU_KEYMANAGER_RSA_PUB_ENCRYPT_USE_CASE;
		}

		if ((CertInfo->KeyUsage & XASU_X509_KEY_USAGE_KEY_AGREEMENT) != 0U) {
			KeyUseCase |= XASU_KEYMANAGER_RSA_PUB_KEY_TRANSPORT_USE_CASE;
		}

		if (CertInfo->PublicKey.RsaPublicKey.ExponentLen == XASUFW_WORD_LEN_IN_BYTES) {
			/** Pack the public exponent at the start of the scratch buffer. */
			Status = Xil_SMemCpy(KeyData, XRSA_PUBEXP_SIZE_IN_BYTES,
					CertInfo->PublicKey.RsaPublicKey.Exponent,
					CertInfo->PublicKey.RsaPublicKey.ExponentLen,
					CertInfo->PublicKey.RsaPublicKey.ExponentLen);
			if (Status != XASUFW_SUCCESS) {
				Status = XASUFW_MEM_COPY_FAIL;
				goto END;
			}
		} else {
			/** Unsupported public exponent size. */
			Status = XASUFW_KEYMANAGER_INVALID_EXPONENT_SIZE;
			goto END;
		}

		/** Append the modulus after the public exponent in the scratch buffer. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = Xil_SMemCpy(&KeyData[XRSA_PUBEXP_SIZE_IN_BYTES], XRSA_4096_KEY_SIZE,
				CertInfo->PublicKey.RsaPublicKey.Modulus,
				CertInfo->PublicKey.RsaPublicKey.ModulusLen,
				CertInfo->PublicKey.RsaPublicKey.ModulusLen);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_MEM_COPY_FAIL;
			goto END;
		}
	} else {
		/** Defensive default; not reachable, since the caller only passes ECC_PUB or
		    RSA_PUB. */
		Status = XASUFW_KEYMANAGER_INVALID_KEY_TYPE;
		goto END;
	}

	/** Initialize parameters for raw key storage. */
	RawKeyParams.KeyMetadata.Length = (u16)KeyLen;
	RawKeyParams.KeyMetadata.UsageCount = KeyParams->KeyMetadata.UsageCount;
	RawKeyParams.KeyMetadata.KeyUseCase = KeyUseCase;
	RawKeyParams.KeyMetadata.KeyAttributes = KeyAttributes;
	RawKeyParams.KeyMetadata.EpochTime = KeyParams->KeyMetadata.EpochTime;
	RawKeyParams.KeyMetadata.CompositeKeyId =
			XASU_KM_COMPOSE_KEY_ID(VaultId, RawKeySubVaultType, 0U);
	RawKeyParams.KeyObjectAddr = 0U;
	RawKeyParams.KeyIdAddr = 0U;

	/** Store the raw public key at the slot the caller resolved. */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_UpdateKeyVault(DmaPtr, RawKeySubVaultType, &RawKeyParams,
					    KeyData, RawSlot, RawKeyIdPtr);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Export the exportable key vault to a user-provided address.
 *
 * @param	DmaPtr			Pointer to the XAsufw_Dma instance.
 * @param	AesInstancePtr		Pointer to the XAes instance.
 * @param	ExportAddr		Address where the entire key vault should be exported.
 * @param	ExportBufSize		Size of the buffer at ExportAddr to prevent overflow.
 * @param	ActualVaultSizeAddr	Address where the actual size of exported vault data will
 *					be stored.
 *
 * @return
 *	- XASUFW_SUCCESS, if key vault export is successful.
 *	- XASUFW_CMD_IN_PROGRESS, if DMA transfer is in progress (non-blocking mode).
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if any input parameter is invalid.
 *	- XASUFW_KEYMANAGER_INVALID_BUF_SIZE, if export buffer is too small.
 *	- XASUFW_KEYMANAGER_AES_KEY_SETUP_FAIL, if AES key setup fails.
 *	- XASUFW_RAND_GEN_ERROR, if TRNG random number generation fails.
 *	- XASUFW_DMA_COPY_FAIL, if DMA transfer fails.
 *	- XASUFW_AES_INIT_FAILED, if AES initialization fails.
 *	- XASUFW_AES_UPDATE_FAILED, if AES update fails.
 *	- XASUFW_AES_FINAL_FAILED, if AES finalization fails.
 *
 *************************************************************************************************/
s32 XKeyManager_ExportKeyVault(XAsufw_Dma *DmaPtr, XAes *AesInstancePtr, u64 ExportAddr,
			       u32 ExportBufSize, u32 ActualVaultSizeAddr)
{
	/**
	 * Capture the start time of the key vault export operation, if performance
	 * measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_START(XASU_MODULE_KEYMANAGER_ID);

	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	CREATE_VOLATILE(ClearStatus, XASUFW_FAILURE);
	u8 *VaultBaseAddr = XKEYMANAGER_GET_VAULT_BASE_PTR();
	u32 *ActualSizePtr = NULL;
	const XKeyManager *KeyVaultPtr = NULL;
	XAsu_AesParams AesParams;
	XAsu_AesKeyObject KeyObject;
	XKeyManager_VaultMainHeader* VaultHeaderPtr = NULL;
	XFih_Var XFihKeyManager = XFih_VolatileAssignXfihVar(XFIH_FAILURE);
	static u8 VaultIndex = XKEYMANAGER_USER_VAULT_START_INDEX;
	static u32 CurrentOutputOffset = 0U;
	static u8 TagBuf[XKEYMANAGER_AES_TAG_LEN_IN_BYTES];
	static u8 KeyIv[XKEYMANAGER_AES_IV_LEN_IN_BYTES];
	static u32 CmdStage = XKEYMANAGER_AES_CMD_STAGE_INIT;
	static u32 RevokeId = 0U;

	/** Validate input parameters. */
	if ((DmaPtr == NULL) || (AesInstancePtr == NULL) || (ExportAddr == 0U) ||
	    (ExportBufSize < XKEYMANAGER_AES_IV_LEN_IN_BYTES) || (ActualVaultSizeAddr == 0U)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	if (VaultBaseAddr == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_DDR_ADDRESS;
		goto END;
	}

	/** Get vault header Address. */
	VaultHeaderPtr = (XKeyManager_VaultMainHeader *)VaultBaseAddr;

	switch (CmdStage) {
	case XKEYMANAGER_AES_CMD_STAGE_INIT:
		/** Store and increment the revoke ID for the vault header. */
		if (IsKeyVaultDirty == XKEYMANAGER_VAULT_DIRTY_VALUE) {
			RevokeId = VaultHeaderPtr->RevokeId;
			VaultHeaderPtr->RevokeId++;
		}

		/** Generate KV KEK and write to AES engine for key vault encryption. */
		Status = XKeyManager_GenerateAndWriteAesKey(DmaPtr, AesInstancePtr);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status,
							  XASUFW_KEYMANAGER_AES_KEY_SETUP_FAIL);
			goto END;
		}

		/** Generate ephemeral Key/IV using TRNG. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XTrng_GetRandomNumbers(KeyIv, XKEYMANAGER_AES_IV_LEN_IN_BYTES);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_RAND_GEN_ERROR;
			goto END_CLR;
		}

		/** Copy IV to export buffer before encryption. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr, (u64)(UINTPTR)KeyIv, ExportAddr,
				       XKEYMANAGER_AES_IV_LEN_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_CLR;
		}

		/** Initialize AES parameters. */
		AesParams.EngineMode = (u8)XASU_AES_GCM_MODE;
		AesParams.OperationType = XASU_AES_ENCRYPT_OPERATION;
		AesParams.KeyObjectAddr = (u64)(UINTPTR)&KeyObject;
		AesParams.IvObj.IvAddr = (u64)(UINTPTR)KeyIv;
		AesParams.IvObj.IvLen = XKEYMANAGER_AES_IV_LEN_IN_BYTES;
		AesParams.AadAddr = (u64)(UINTPTR)KeyIv;
		AesParams.AadLen = XKEYMANAGER_AES_IV_LEN_IN_BYTES;
		AesParams.TagAddr = (u64)(UINTPTR)TagBuf;
		AesParams.TagLen = XKEYMANAGER_AES_TAG_LEN_IN_BYTES;

		/** Initialize the AES engine for the given AES operation. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Init(AesInstancePtr, DmaPtr, AesParams.IvObj.IvAddr,
				   AesParams.IvObj.IvLen, AesParams.EngineMode,
				   AesParams.OperationType);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_INIT_FAILED);
			goto END_CLR;
		}

		/** Update AAD. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Update(AesInstancePtr, DmaPtr, AesParams.AadAddr, 0U,
				     AesParams.AadLen, XASU_FALSE);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
			goto END_CLR;
		}

		/** Move data offsets to the keyvault data. */
		CurrentOutputOffset = XKEYMANAGER_AES_IV_LEN_IN_BYTES +
					XKEYMANAGER_VAULT_MAIN_HEADER_SIZE;

		/* fall through */
	case XKEYMANAGER_AES_CMD_STAGE_UPDATE_INPROGRESS:
		/** Encrypt each individual vault except ASU vault (index 0). */
		for (; VaultIndex < XASU_KM_MAX_VAULTS; VaultIndex++) {
			KeyVaultPtr = (XKeyManager *)VaultManager.VaultInfo[VaultIndex].VaultBasePtr;
			if ((VaultManager.VaultInfo[VaultIndex].VaultSize == 0U) ||
			    (!XKEYMANAGER_IS_VAULT_EXPORTABLE(KeyVaultPtr->Header.Restrictions))) {
				/** Skip non-exportable or empty vaults. */
				continue;
			}

			/** Check if the export buffer has enough space for the current vault. */
			if (ExportBufSize < (CurrentOutputOffset + VaultManager.VaultInfo[VaultIndex].VaultSize)) {
				Status = XASUFW_KEYMANAGER_INVALID_BUF_SIZE;
				goto END_CLR;
			}

			/** Encrypt this vault's data. */
			Status = XAes_Update(AesInstancePtr, DmaPtr,
					     (u64)(UINTPTR)KeyVaultPtr,
					     ExportAddr + CurrentOutputOffset,
					     VaultManager.VaultInfo[VaultIndex].VaultSize,
					     XASU_FALSE);

			/** Update offsets after successful synchronous encryption. */
			CurrentOutputOffset += VaultManager.VaultInfo[VaultIndex].VaultSize;

			if (Status == XASUFW_CMD_IN_PROGRESS) {
				/**
				 * DMA transfer is in progress for current vault.
				 * Update offsets and increment VaultIndex for the next iteration.
				 */
				CmdStage = XKEYMANAGER_AES_CMD_STAGE_UPDATE_INPROGRESS;
				VaultIndex++;
				goto END;
			} else if (Status != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
				goto END_CLR;
			} else {
				/* Do nothing. */
			}
		}

		/** Encrypt main vault header. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Update(AesInstancePtr, DmaPtr, (u64)(UINTPTR)VaultBaseAddr,
				     ExportAddr + XKEYMANAGER_AES_IV_LEN_IN_BYTES,
				     XKEYMANAGER_VAULT_MAIN_HEADER_SIZE,
				     XASU_TRUE);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
			goto END_CLR;
		}

		/** Finalize AES operation and generate tag. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Final(AesInstancePtr, DmaPtr, (u64)(UINTPTR)TagBuf,
				    XKEYMANAGER_AES_TAG_LEN_IN_BYTES);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_FINAL_FAILED);
			goto END_CLR;
		}

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		/** Check if the export buffer has enough space for the tag. */
		if (ExportBufSize < (CurrentOutputOffset + XKEYMANAGER_AES_TAG_LEN_IN_BYTES)) {
			Status = XASUFW_KEYMANAGER_INVALID_BUF_SIZE;
			goto END_CLR;
		}

		/** Copy the generated tag to the export buffer after encrypted data. */
		Status = XAsufw_DmaXfr(DmaPtr, (u64)(UINTPTR)TagBuf,
				       ExportAddr + CurrentOutputOffset,
				       XKEYMANAGER_AES_TAG_LEN_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_CLR;
		}

		/** Write actual vault size (IV + encrypted data + GCM tag) to output parameter. */
		ActualSizePtr = (u32 *)(UINTPTR)ActualVaultSizeAddr;
		*ActualSizePtr = CurrentOutputOffset + XKEYMANAGER_AES_TAG_LEN_IN_BYTES;

		/** Mark the key vault as clean after successful export. */
		IsKeyVaultDirty = XKEYMANAGER_VAULT_CLEAN_VALUE;

		break;
	default:
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		break;
	}

	/**
	 * Measure and print the performance time for the key vault export operation, if
	 * performance measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_STOP(XASU_MODULE_KEYMANAGER_ID);

END_CLR:
	/** Zeroize the IV buffer. */
	ClearStatus = Xil_SecureZeroize(KeyIv, XKEYMANAGER_AES_IV_LEN_IN_BYTES);
	Status = XAsufw_UpdateErrorStatus(Status, ClearStatus);

	/** Clear the key written to the XASU_AES_USER_KEY_7 key source. */
	XFIH_CALL(XAes_KeyClear, XFihKeyManager, ClearStatus, AesInstancePtr, XASU_AES_USER_KEY_7);
	Status = XAsufw_UpdateErrorStatus(Status, ClearStatus);

	/** Zeroize the key object. */
	ClearStatus = Xil_SecureZeroize((u8 *)(UINTPTR)&KeyObject, sizeof(XAsu_AesKeyObject));
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

	/** Zeroize the local tag buffer. */
	ClearStatus = Xil_SecureZeroize((u8 *)(UINTPTR)TagBuf, XKEYMANAGER_AES_TAG_LEN_IN_BYTES);
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

	/** Reset vault index and offsets after operation. */
	VaultIndex = XKEYMANAGER_USER_VAULT_START_INDEX;
	CurrentOutputOffset = 0U;
	CmdStage = XKEYMANAGER_AES_CMD_STAGE_INIT;

END:
	/** Restore revoke ID in case of failure in key vault export. */
	if ((Status != XASUFW_SUCCESS) && (Status != XASUFW_CMD_IN_PROGRESS) &&
	    (IsKeyVaultDirty == XKEYMANAGER_VAULT_DIRTY_VALUE) && (VaultHeaderPtr != NULL)) {
		VaultHeaderPtr->RevokeId = RevokeId;
	}
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Import the entire key vault from a user-provided address.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	AesInstancePtr	Pointer to the XAes instance.
 * @param	ImportAddr	Address where the encrypted vault data is located.
 * @param	ImportSize	Total size of the import data (including IV and GCM tag).
 *
 * @return
 *	- XASUFW_SUCCESS, if key vault import is successful.
 *	- XASUFW_CMD_IN_PROGRESS, if DMA transfer is in progress (non-blocking mode).
 *	- XASUFW_KEYMANAGER_INVALID_PARAM, if any input parameter is invalid.
 *	- XASUFW_ZEROIZE_MEMSET_FAIL, if memory zeroization fails.
 *	- XASUFW_DMA_COPY_FAIL, if DMA transfer fails.
 *	- XASUFW_KEYMANAGER_AES_KEY_SETUP_FAIL, if AES key setup fails.
 *	- XASUFW_AES_INIT_FAILED, if AES initialization fails.
 *	- XASUFW_AES_UPDATE_FAILED, if AES update fails.
 *	- XASUFW_AES_FINAL_FAILED, if AES finalization fails.
 *	- XASUFW_KEYMANAGER_INVALID_ID_STRING, if imported vault header contains invalid ID string.
 *	- XASUFW_KEYMANAGER_INVALID_VAULT_VERSION, if imported vault header contains unsupported
 *	version.
 *	- XASUFW_KEYMANAGER_INVALID_VAULT_ID, if imported vault header contains invalid vault ID.
 *
 *************************************************************************************************/
s32 XKeyManager_ImportKeyVault(XAsufw_Dma *DmaPtr, XAes *AesInstancePtr, u64 ImportAddr,
			       u32 ImportSize)
{
	/**
	 * Capture the start time of the key vault import operation, if performance
	 * measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_START(XASU_MODULE_KEYMANAGER_ID);

	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	CREATE_VOLATILE(ClearStatus, XASUFW_FAILURE);
	u8 *VaultBaseAddr = XKEYMANAGER_GET_VAULT_BASE_PTR();
	u8 *ActualDataPtr = NULL;
	u8 Index = 0U;
	u8 RevokeId = 0U;
	u8 VaultMainHeader[XKEYMANAGER_VAULT_MAIN_HEADER_SIZE] = {0U};
	u32 VaultId = 0U;
	u32 ImportDataOffset = 0U;
	u32 EncryptedDataSize = 0U;
	XAsu_AesParams AesParams;
	XAsu_AesKeyObject KeyObject;
	XKeyManager *ImportedVaultPtr = NULL;
	XKeyManager_VaultMainHeader *VaultHeaderPtr = NULL;
	const XKeyManager_VaultMainHeader *ImportedVaultHeaderPtr = NULL;
	XFih_Var XFihKeyManager = XFih_VolatileAssignXfihVar(XFIH_FAILURE);
	static u8 KeyIv[XKEYMANAGER_AES_IV_LEN_IN_BYTES];
	static u8 TagBuf[XKEYMANAGER_AES_TAG_LEN_IN_BYTES];
	static u32 CmdStage = XKEYMANAGER_AES_CMD_STAGE_INIT;
	u32 UserVaultLen = 0U;

	/** Validate input parameters. */
	if ((DmaPtr == NULL) || (AesInstancePtr == NULL) || (ImportAddr == 0U) ||
	    (ImportSize < (XKEYMANAGER_AES_IV_LEN_IN_BYTES + XKEYMANAGER_AES_TAG_LEN_IN_BYTES +
			   XKEYMANAGER_VAULT_MAIN_HEADER_SIZE))) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	if (VaultBaseAddr == NULL) {
		Status = XASUFW_KEYMANAGER_INVALID_DDR_ADDRESS;
		goto END;
	}

	/** Get vault header Address. */
	VaultHeaderPtr = (XKeyManager_VaultMainHeader *)VaultBaseAddr;

	/** Calculate encrypted data size (excluding IV and GCM tag). */
	EncryptedDataSize = (ImportSize - XKEYMANAGER_AES_IV_LEN_IN_BYTES -
				XKEYMANAGER_AES_TAG_LEN_IN_BYTES);
	UserVaultLen = VaultManager.TotalVaultSize - XKEYMANAGER_VAULT_MAIN_HEADER_SIZE -
			VaultManager.VaultInfo[XKEYMANAGER_ASU_VAULT_ID].VaultSize ;

	/** Validate sufficient space is available for decrypted data. */
	if (EncryptedDataSize > (UserVaultLen + XKEYMANAGER_VAULT_MAIN_HEADER_SIZE)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Skip ASU key vault to avoid override. */
	ActualDataPtr = VaultBaseAddr + XKEYMANAGER_VAULT_MAIN_HEADER_SIZE +
				VaultManager.VaultInfo[XKEYMANAGER_ASU_VAULT_ID].VaultSize;

	switch (CmdStage) {
	case XKEYMANAGER_AES_CMD_STAGE_INIT:
		/** Clear entire user vault region (excluding ASU vault and main header). */
		Status = Xil_SMemSet(ActualDataPtr, UserVaultLen, 0U, UserVaultLen);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_ZEROIZE_MEMSET_FAIL;
			goto END;
		}

		/** Clear existing vault registry except ASU vault (index 0). */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = Xil_SMemSet(&VaultManager.VaultInfo[XKEYMANAGER_USER_VAULT_START_INDEX],
				     (XASU_KM_MAX_VAULTS - XKEYMANAGER_USER_VAULT_START_INDEX) *
				     sizeof(XKeyManager_VaultInfo), 0U,
				     (XASU_KM_MAX_VAULTS - XKEYMANAGER_USER_VAULT_START_INDEX) *
				     sizeof(XKeyManager_VaultInfo));
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_ZEROIZE_MEMSET_FAIL;
			goto END;
		}
		VaultManager.RemainingVaultSize = VaultManager.TotalVaultSize -
					XKEYMANAGER_VAULT_MAIN_HEADER_SIZE -
					VaultManager.VaultInfo[XKEYMANAGER_ASU_VAULT_ID].VaultSize;

		/** Generate KV KEK and write to AES engine for key vault decryption. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XKeyManager_GenerateAndWriteAesKey(DmaPtr, AesInstancePtr);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status,
							  XASUFW_KEYMANAGER_AES_KEY_SETUP_FAIL);
			goto END;
		}

		/** Read IV from the beginning of import buffer. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr, ImportAddr, (u64)(UINTPTR)KeyIv,
				       XKEYMANAGER_AES_IV_LEN_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_CLR;
		}

		/** Read GCM tag from the end of import buffer. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAsufw_DmaXfr(DmaPtr,
				       ImportAddr + ImportSize - XKEYMANAGER_AES_TAG_LEN_IN_BYTES,
				       (u64)(UINTPTR)TagBuf, XKEYMANAGER_AES_TAG_LEN_IN_BYTES, 0U);
		if (Status != XASUFW_SUCCESS) {
			Status = XASUFW_DMA_COPY_FAIL;
			goto END_CLR;
		}

		/** Initialize AES parameters for decryption. */
		AesParams.EngineMode = (u8)XASU_AES_GCM_MODE;
		AesParams.OperationType = XASU_AES_DECRYPT_OPERATION;
		AesParams.KeyObjectAddr = (u64)(UINTPTR)&KeyObject;
		AesParams.IvObj.IvAddr = (u64)(UINTPTR)KeyIv;
		AesParams.IvObj.IvLen = XKEYMANAGER_AES_IV_LEN_IN_BYTES;
		AesParams.AadAddr = (u64)(UINTPTR)KeyIv;
		AesParams.AadLen = XKEYMANAGER_AES_IV_LEN_IN_BYTES;
		AesParams.TagAddr = (u64)(UINTPTR)TagBuf;
		AesParams.TagLen = XKEYMANAGER_AES_TAG_LEN_IN_BYTES;

		/** Initialize the AES engine for decryption. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Init(AesInstancePtr, DmaPtr, AesParams.IvObj.IvAddr,
				   AesParams.IvObj.IvLen, AesParams.EngineMode,
				   AesParams.OperationType);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_INIT_FAILED);
			goto END_CLR;
		}

		/** Update AAD with IV for ensuring authenticity and integrity. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Update(AesInstancePtr, DmaPtr, AesParams.AadAddr, 0U,
				     AesParams.AadLen, XASU_FALSE);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
			goto END_CLR;
		}

		if (EncryptedDataSize > XKEYMANAGER_VAULT_MAIN_HEADER_SIZE) {
			ImportDataOffset = XKEYMANAGER_AES_IV_LEN_IN_BYTES +
						XKEYMANAGER_VAULT_MAIN_HEADER_SIZE;
			/** Decrypt the vault data (excluding IV at start and GCM tag at end). */
			ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
			Status = XAes_Update(AesInstancePtr, DmaPtr, ImportAddr + ImportDataOffset,
					     (u64)(UINTPTR)ActualDataPtr,
					     EncryptedDataSize - XKEYMANAGER_VAULT_MAIN_HEADER_SIZE,
					     XASU_FALSE);
			if (Status == XASUFW_CMD_IN_PROGRESS) {
				CmdStage = XKEYMANAGER_AES_CMD_STAGE_UPDATE_INPROGRESS;
				goto END;
			} else if (Status != XASUFW_SUCCESS) {
				Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
				goto END_CLR;
			} else {
				/* Do nothing. */
			}
		}

		/* fall through */
	case XKEYMANAGER_AES_CMD_STAGE_UPDATE_INPROGRESS:
		/** Decrypt main vault header. */
		Status = XAes_Update(AesInstancePtr, DmaPtr,
				     ImportAddr + XKEYMANAGER_AES_IV_LEN_IN_BYTES,
				     (u64)(UINTPTR)VaultMainHeader,
				     XKEYMANAGER_VAULT_MAIN_HEADER_SIZE, XASU_TRUE);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_UPDATE_FAILED);
			goto END_CLR;
		}

		/** Finalize AES operation and validate GCM tag. */
		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		Status = XAes_Final(AesInstancePtr, DmaPtr, (u64)(UINTPTR)TagBuf,
				    XKEYMANAGER_AES_TAG_LEN_IN_BYTES);
		if (Status != XASUFW_SUCCESS) {
			Status = XAsufw_UpdateErrorStatus(Status, XASUFW_AES_FINAL_FAILED);
			goto END_CLR;
		}

		ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
		/** Map decrypted main header to the vault header structure. */
		ImportedVaultHeaderPtr = (XKeyManager_VaultMainHeader *)VaultMainHeader;

		/** Validate key vault identification string. */
		if (ImportedVaultHeaderPtr->KeyVaultHeader != XKEYMANAGER_IDENTIFICATION_STRING) {
			Status = XASUFW_KEYMANAGER_INVALID_ID_STRING;
			goto END_CLR;
		}

		/** Validate major and minor version. */
		if ((ImportedVaultHeaderPtr->MajorVersion != XKEYMANAGER_MAJOR_VERSION) ||
		    (ImportedVaultHeaderPtr->MinorVersion != XKEYMANAGER_MINOR_VERSION)) {
			Status = XASUFW_KEYMANAGER_INVALID_VAULT_VERSION;
			goto END_CLR;
		}

		/** Reconstruct vault main header. */
		VaultHeaderPtr->KeyVaultHeader = ImportedVaultHeaderPtr->KeyVaultHeader;
		VaultHeaderPtr->MajorVersion = ImportedVaultHeaderPtr->MajorVersion;
		VaultHeaderPtr->MinorVersion = ImportedVaultHeaderPtr->MinorVersion;
		VaultHeaderPtr->RevokeId= ImportedVaultHeaderPtr->RevokeId;

		/**
		 * Validate revoke ID to detect importing older vault versions that should have been
		 * revoked. The revoke ID in the vault header is incremented whenever key vault is
		 * exported after updation. User is expected to revoke earlier version of key vault by
		 * programmatically burning OFFCHIP_REVOKE eFuse bits before importing newer version of
		 * key vault. If the revoke ID in the imported vault is less than the current
		 * revoke ID, it indicates that this vault version has been revoked and should not
		 * be imported.
		 */
		RevokeId = XKeyManager_GetRevokeId();
		if (ImportedVaultHeaderPtr->RevokeId <= RevokeId) {
			Status = XASUFW_KEYMANAGER_VAULT_REVOKE_ID_MISMATCH;
			goto END_CLR;
		}

		/** Update remaining vault size after clearing existing vaults. */
		VaultManager.RemainingVaultSize = VaultManager.TotalVaultSize -
					VaultManager.VaultInfo[XKEYMANAGER_ASU_VAULT_ID].VaultSize -
					EncryptedDataSize;

		/**
		 * Scan through decrypted vault to rebuild vault info.
		 * First vault starts after the main header, subsequent vaults are contiguous.
		 */
		ImportedVaultPtr = (XKeyManager *)ActualDataPtr;

		for (Index = XKEYMANAGER_USER_VAULT_START_INDEX; (Index < XASU_KM_MAX_VAULTS);
		     Index++) {
			/** Check if the current vault is empty. */
			if (ImportedVaultPtr->Header.VaultSize == 0U) {
				break;
			}

			/** Get the vault ID from the imported vault header. */
			VaultId = ImportedVaultPtr->Header.KeyVaultId;
			if (VaultId >= XASU_KM_MAX_VAULTS) {
				Status = XASUFW_KEYMANAGER_INVALID_VAULT_ID;
				goto END_CLR;
			}

			/** Reconstruct vault info from imported vault header. */
			VaultManager.VaultInfo[VaultId].VaultBasePtr = (u32 *)ImportedVaultPtr;
			VaultManager.VaultInfo[VaultId].VaultSize = ImportedVaultPtr->Header.VaultSize;
			VaultManager.VaultInfo[VaultId].SubSystemId = ImportedVaultPtr->Header.SubSystemId;

			/** Move to next vault. */
			ImportedVaultPtr = (XKeyManager *)((u8 *)ImportedVaultPtr +
					   ImportedVaultPtr->Header.VaultSize);
		}

		Status = XASUFW_SUCCESS;
		break;
	default:
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		break;
	}

	/**
	 * Measure and print the performance time for the key vault import operation, if
	 * performance measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_STOP(XASU_MODULE_KEYMANAGER_ID);

END_CLR:
	/** Zeroize the IV buffer. */
	ClearStatus = Xil_SecureZeroize(KeyIv, XKEYMANAGER_AES_IV_LEN_IN_BYTES);
	Status = XAsufw_UpdateErrorStatus(Status, ClearStatus);

	/** Clear the key written to the XASU_AES_USER_KEY_7 key source. */
	XFIH_CALL(XAes_KeyClear, XFihKeyManager, ClearStatus, AesInstancePtr, XASU_AES_USER_KEY_7);
	Status = XAsufw_UpdateErrorStatus(Status, ClearStatus);

	/** Zeroize the key object. */
	ClearStatus = Xil_SecureZeroize((u8 *)(UINTPTR)&KeyObject, sizeof(XAsu_AesKeyObject));
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

	/** Zeroize the local tag buffer. */
	ClearStatus = Xil_SecureZeroize((u8 *)(UINTPTR)TagBuf, XKEYMANAGER_AES_TAG_LEN_IN_BYTES);
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

	/** Reset command stage after decryption is complete. */
	CmdStage = XKEYMANAGER_AES_CMD_STAGE_INIT;

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Read the offchip revoke efuse registers to determine the current revoke ID,
 *		which is represented by the index of the last bit set across the 8 revoke registers.
 *
 * @return
 *	- Return revoke ID as the index of the last efuse bit set.
 *	- If no bits are set, returns 0.
 *
 *************************************************************************************************/
static inline u8 XKeyManager_GetRevokeId(void)
{
	u32 RegValue;
	u8 LastBitIndex = 0U;
	s8 RegIdx;
	s8 BitIdx;

	/**
	 * Scan through all 8 registers (32 bytes = 256 bits total) starting from the
	 * last register and MSB to find the index of the last (highest) bit that is set.
	 */
	for (RegIdx = XKEYMANAGER_MAX_REVOKE_REG_INDEX; RegIdx >= 0; RegIdx--) {
		RegValue = XAsufw_ReadReg(EFUSE_CACHE_OFFCHIP_REVOKE_0_ADDR + ((u32)RegIdx *
					  XASUFW_WORD_LEN_IN_BYTES));

		/** Check each bit in the current register from MSB to LSB. */
		if (RegValue != 0U) {
			for (BitIdx = XASUFW_MAX_BIT_INDEX_IN_WORD; BitIdx >= 0; BitIdx--) {
				if ((RegValue & ((u32)1U << (u8)BitIdx)) != 0U) {
					LastBitIndex = ((u8)RegIdx * XASUFW_BITS_IN_WORD) + (u8)BitIdx;
					goto END;
				}
			}
		}
	}

END:
	return LastBitIndex;
}

