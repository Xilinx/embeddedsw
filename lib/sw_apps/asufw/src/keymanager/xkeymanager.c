/*************************************************************************************************/
/**
 * @brief	This function generates a key by combining two AES key splits using a bitwise XOR
 *		and stores the combined key in the key vault slot given by the output key metadata,
 *		or in the first free slot when none is requested. The key splits are read in place
 *		from the key vault and the combined key is formed in an internal buffer, so the
 *		combined key is never exposed outside the ASU other than through the destination
 *		key vault slot. Each input key must carry the key split use case and no other use
 *		case, which prevents it from being used as a key in its own right. Each input key
 *		split's usage count is decremented exactly once, and only after the combined key
 *		has been stored, so no failure before the store consumes a split's use. Both splits
 *		are consumed after the store and consumption cannot fail, so one split is never
 *		consumed without the other. The composite key ID of the stored key is written to
 *		KeyIdPtr.
 *
 * @param	DmaPtr		Pointer to the XAsufw_Dma instance.
 * @param	SubSystemId	Subsystem ID requesting the operation.
 * @param	ParamsPtr	Pointer to the XAsu_KmXorKeyParams structure containing the input
 *				key IDs and the metadata of the combined key.
 * @param	KeyIdPtr	Pointer to the output composite key ID of the combined key.
 *
 * @return
 * 	- XASUFW_SUCCESS, if the combined key is stored successfully.
 * 	- XASUFW_KEYMANAGER_INVALID_PARAM, if any input parameter is invalid, or the requested key
 * 		slot exceeds the sub-vault capacity.
 * 	- XASUFW_KEYMANAGER_INVALID_VAULT_ACCESS, if the subsystem does not own the output vault.
 * 	- XASUFW_KEYMANAGER_KEY_SLOT_IN_USE, if the requested key slot is already occupied.
 * 	- XASUFW_KEYMANAGER_MAX_CAPACITY_REACHED, if the AES sub-vault has no free slot.
 * 	- Error code propagated from XKeyManager_GetKeyObjectPtr, if an input key split is
 * 		unavailable, is not accessible to the subsystem, or is expired.
 * 	- XASUFW_KEYMANAGER_KEY_USE_CASE_ERROR, if an input key carries any use case other than
 * 		the key split use case.
 * 	- XASUFW_KEYMANAGER_KEY_LENGTH_MISMATCH, if the input key split lengths differ from each
 * 		other or from the length declared in the output key metadata.
 * 	- XASUFW_LOOP_INDEX_CMP_ERROR, if the XOR combine loop does not complete.
 * 	- XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL, if the key slot cannot be resolved, packed
 * 		with the specific slot resolution error.
 * 	- Error codes returned by XKeyManager_UpdateKeyVault, if storing the combined key fails.
 *
 *************************************************************************************************/
s32 XKeyManager_CombineKeysXor(XAsufw_Dma *DmaPtr, u32 SubSystemId,
	const XAsu_KmXorKeyParams *ParamsPtr, u32 *KeyIdPtr)
{
	/**
	 * Capture the start time of the XOR key combine operation, if performance
	 * measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_START(XASU_MODULE_KEYMANAGER_ID);

	CREATE_VOLATILE(Status, XASUFW_FAILURE);
	XFih_Var XFihKeyManager = XFih_VolatileAssignXfihVar(XFIH_FAILURE);
	s32 ClearStatus = XASUFW_FAILURE;
	const XKeyManager_AesKeyObject *SplitKeyAPtr = NULL;
	const XKeyManager_AesKeyObject *SplitKeyBPtr = NULL;
	const u8 *KeyObjPtr = NULL;
	u8 *SplitKeyAAddr = NULL;
	u8 *SplitKeyBAddr = NULL;
	u8 CombinedKey[XASU_AES_KEY_SIZE_256BIT_IN_BYTES] = {0U};
	XAsu_KeyManagerParams UpdateParams = {0U};
	u16 ResolvedSlot = 0U;
	u8 OutVaultId;
	u32 KeyLength = 0U;
	volatile u32 Index = 0U;

	/** Validate input parameters. */
	if ((DmaPtr == NULL) || (ParamsPtr == NULL) || (KeyIdPtr == NULL)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Clear the returned key ID so no failure path leaves the caller a stale value. */
	*KeyIdPtr = 0U;

	Status = XAsu_KmValidateXorKeyParams(ParamsPtr);
	if (Status != XASUFW_SUCCESS) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	OutVaultId = XASU_KM_GET_VAULT_ID(ParamsPtr->OutKeyMetadata.CompositeKeyId);

	/**
	 * Both input key splits must be AES keys. The key type of the output key is validated in
	 * XAsu_KmValidateXorKeyParams.
	 */
	if ((XASU_KM_GET_KEY_TYPE(ParamsPtr->SplitKeyId1) != (u8)XASU_AES_SUBVAULT_ID) ||
	    (XASU_KM_GET_KEY_TYPE(ParamsPtr->SplitKeyId2) != (u8)XASU_AES_SUBVAULT_ID)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/** Validate the vault exists and belongs to the subsystem. */
	if ((VaultManager.VaultInfo[OutVaultId].VaultSize == 0U) ||
	    (VaultManager.VaultInfo[OutVaultId].SubSystemId != SubSystemId)) {
		Status = XASUFW_KEYMANAGER_INVALID_VAULT_ACCESS;
		goto END;
	}

	/**
	 * Resolve the destination slot before either key split is consumed, so a slot conflict
	 * does not deplete their usage counts. An occupied slot is rejected here, which also
	 * covers a request naming the slot of one of the input key splits.
	 */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetKeySlot(OutVaultId, XASU_AES_SUBVAULT_ID,
			XASU_KM_GET_KEY_INDEX(ParamsPtr->OutKeyMetadata.CompositeKeyId),
			&ResolvedSlot);
	if (Status != XASUFW_SUCCESS) {
		Status = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_KEY_VAULT_FAIL);
		goto END;
	}

	/**
	 * Resolve and validate both input key splits without consuming them (IsKeyUsed = FALSE).
	 * This validates the vault access rights, the key split use case and the key expiry for
	 * each split, but leaves their usage counts untouched. The usage counts are decremented
	 * only after the combined key has been stored (see the second pass below), so a failure
	 * on the second split lookup, a metadata check or the store itself never consumes a use
	 * from the first split.
	 *
	 * The writable address of each split is resolved alongside the read-only one, so the
	 * second pass consumes the use through the key object resolved here instead of repeating
	 * the lookup and its checks.
	 */
	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetKeyObjectPtr(ParamsPtr->SplitKeyId1, SubSystemId,
				XASU_KEYMANAGER_AES_KEY_SPLIT_USE_CASE, FALSE,
				&KeyObjPtr);
	if (Status != XASUFW_SUCCESS) {
		goto END;
	}
	SplitKeyAPtr = (const XKeyManager_AesKeyObject *)KeyObjPtr;
	SplitKeyAAddr = XKeyManager_GetKeyObjectAddr(XASU_KM_GET_VAULT_ID(ParamsPtr->SplitKeyId1),
				(u8)XASU_AES_SUBVAULT_ID,
				XASU_KM_GET_KEY_INDEX(ParamsPtr->SplitKeyId1));

	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	Status = XKeyManager_GetKeyObjectPtr(ParamsPtr->SplitKeyId2, SubSystemId,
				XASU_KEYMANAGER_AES_KEY_SPLIT_USE_CASE, FALSE,
				&KeyObjPtr);
	if (Status != XASUFW_SUCCESS) {
		goto END;
	}
	SplitKeyBPtr = (const XKeyManager_AesKeyObject *)KeyObjPtr;
	SplitKeyBAddr = XKeyManager_GetKeyObjectAddr(XASU_KM_GET_VAULT_ID(ParamsPtr->SplitKeyId2),
				(u8)XASU_AES_SUBVAULT_ID,
				XASU_KM_GET_KEY_INDEX(ParamsPtr->SplitKeyId2));

	/**
	 * Both addresses resolve the slots the lookups above just validated, so a NULL here would
	 * mean the two resolve paths disagree. Reject that rather than consume a use through a
	 * pointer which cannot be trusted.
	 */
	if ((SplitKeyAAddr == NULL) || (SplitKeyBAddr == NULL)) {
		Status = XASUFW_KEYMANAGER_INVALID_PARAM;
		goto END;
	}

	/**
	 * Require the key split use case to be the only use case set. Creation of a key with a
	 * mixed use case is rejected by XAsu_KmValidateKeyMetadata, so this guards against a key
	 * vault imported from an image which predates that check.
	 */
	if ((SplitKeyAPtr->Metadata.KeyUseCase != XASU_KEYMANAGER_AES_KEY_SPLIT_USE_CASE) ||
	    (SplitKeyBPtr->Metadata.KeyUseCase != XASU_KEYMANAGER_AES_KEY_SPLIT_USE_CASE)) {
		Status = XASUFW_KEYMANAGER_KEY_USE_CASE_ERROR;
		goto END;
	}

	/**
	 * A bitwise XOR preserves the operand length, so both input key splits and the declared
	 * length of the combined key must agree.
	 */
	KeyLength = (u32)SplitKeyAPtr->Metadata.Length;
	if ((KeyLength != (u32)SplitKeyBPtr->Metadata.Length) ||
	    (KeyLength != (u32)ParamsPtr->OutKeyMetadata.Length) ||
	    (KeyLength > XASU_AES_KEY_SIZE_256BIT_IN_BYTES)) {
		Status = XASUFW_KEYMANAGER_KEY_LENGTH_MISMATCH;
		goto END;
	}

	/** Combine the two key splits using a bitwise XOR. */
	for (Index = 0U; Index < KeyLength; Index++) {
		CombinedKey[Index] = SplitKeyAPtr->Content[Index] ^ SplitKeyBPtr->Content[Index];
	}

	if (Index != KeyLength) {
		Status = XASUFW_LOOP_INDEX_CMP_ERROR;
		goto END;
	}

	ASSIGN_VOLATILE(Status, XASUFW_FAILURE);
	/** Store the combined key at the resolved key vault slot. */
	UpdateParams.KeyMetadata = ParamsPtr->OutKeyMetadata;
	Status = XKeyManager_UpdateKeyVault(DmaPtr, XASU_AES_SUBVAULT_ID, &UpdateParams,
		CombinedKey, ResolvedSlot, KeyIdPtr);
	if (Status != XASUFW_SUCCESS) {
		goto END;
	}

	/**
	 * Consume one use from each input key split, as the final step now that the combined key
	 * is stored. Deferring the decrement to here ensures no earlier failure (the second split
	 * lookup, a metadata check or the store) ever consumes a split. Both uses are consumed
	 * through the key objects resolved above, which cannot fail, so there is no state in
	 * which one split has been consumed and the other has not.
	 */
	XKeyManager_ConsumeKeyUse(SplitKeyAAddr, XASU_KM_GET_VAULT_ID(ParamsPtr->SplitKeyId1));
	XKeyManager_ConsumeKeyUse(SplitKeyBAddr, XASU_KM_GET_VAULT_ID(ParamsPtr->SplitKeyId2));

	/**
	 * Measure and print the performance time for the XOR key combine operation, if
	 * performance measurement is enabled.
	 */
	XASUFW_MEASURE_PERF_STOP(XASU_MODULE_KEYMANAGER_ID);

END:
	/** Securely zeroize the combined key buffer. */
	XFIH_CALL(Xil_SecureZeroize, XFihKeyManager, ClearStatus, CombinedKey,
			XASU_AES_KEY_SIZE_256BIT_IN_BYTES);
	Status = XAsufw_UpdateBufStatus(Status, ClearStatus);

	return Status;
}

/*************************************************************************************************/
/**
 * @brief	Roll back a key pair whose public half could not be stored. The private half is
 *		already in the vault, so a delete is attempted and both output key IDs are cleared,
 *		which keeps a caller from reading back a handle to a key that no longer exists.
 *		The key ID clearing is unconditional, but the delete is best effort: if the delete
 *		fails, the private half stays in the vault and keeps its slot in use, while the
 *		cleared key IDs leave the caller no handle to retry the delete with. That case is
 *		reported only through the buffer clear status field of the returned status, so the
 *		rollback is not a guarantee that a failed pair leaves nothing behind. Shared
 *		by the RSA, ECC, ML-DSA and ML-KEM key pair generators so the rule holds in one
 *		place.
 *
 * @param	KeyIdPtr	Pointer to the two output key IDs, both cleared by this function.
 * @param	SubSystemId	Subsystem the private half was stored for.
 * @param	Status		Failure status returned by the public half store.
 *
 * @return
 *	- The public half store failure packed with XASUFW_KEYMANAGER_UPDATE_PUB_KEY_FAIL, and
 *	  with the buffer clear status field marked failed if the delete fails or if either key ID
 *	  does not read back as cleared.
 *
 *************************************************************************************************/
static s32 XKeyManager_RollbackKeyPair(u32 *KeyIdPtr, u32 SubSystemId, s32 Status)
{
	CREATE_VOLATILE(RollbackStatus, XASUFW_FAILURE);
	CREATE_VOLATILE(DeleteStatus, XASUFW_FAILURE);
	volatile u32 *KeyIdVolatilePtr = (volatile u32 *)KeyIdPtr;

	/* Status holds the cause from XKeyManager_UpdateKeyVault, retain it. */
	RollbackStatus = XAsufw_UpdateErrorStatus(Status, XASUFW_KEYMANAGER_UPDATE_PUB_KEY_FAIL);

	/**
	 * Delete the private half so a failed pair leaves no orphan key. A delete which itself
	 * fails is only recorded in the buffer clear status field below: the private half then
	 * stays in the vault, holding its slot, and the key IDs are cleared regardless.
	 */
	DeleteStatus = XKeyManager_DeleteKey(KeyIdVolatilePtr[XKEYMANAGER_PVT_KEY_ID_OFFSET],
						SubSystemId);

	/** Clear both key IDs so no handle to a deleted key is returned. */
	KeyIdVolatilePtr[XKEYMANAGER_PVT_KEY_ID_OFFSET] = 0U;
	KeyIdVolatilePtr[XKEYMANAGER_PUB_KEY_ID_OFFSET] = 0U;

	/**
	 * Read both IDs back through the volatile pointer and clear them again. The IDs are written
	 * into the command response buffer, so a store the compiler elided or a glitch skipped
	 * would hand the caller a live handle to the key just deleted. A second pass is recorded in
	 * the buffer clear status field.
	 */
	if ((KeyIdVolatilePtr[XKEYMANAGER_PVT_KEY_ID_OFFSET] != 0U) ||
		(KeyIdVolatilePtr[XKEYMANAGER_PUB_KEY_ID_OFFSET] != 0U)) {
		KeyIdVolatilePtr[XKEYMANAGER_PVT_KEY_ID_OFFSET] = 0U;
		KeyIdVolatilePtr[XKEYMANAGER_PUB_KEY_ID_OFFSET] = 0U;
		RollbackStatus = XAsufw_UpdateBufStatus(RollbackStatus, XASUFW_FAILURE);
	}

	if (DeleteStatus != XASUFW_SUCCESS) {
		RollbackStatus = XAsufw_UpdateBufStatus(RollbackStatus, DeleteStatus);
	}

	return RollbackStatus;
}

