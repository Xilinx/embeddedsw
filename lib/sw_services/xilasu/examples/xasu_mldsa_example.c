/**
 * @brief	Main function to demonstrate the ML-DSA client APIs.
 *
 * @return
 *		- XST_SUCCESS if example runs successfully.
 *		- ErrorCode if the example fails.
 *
 *************************************************************************************************/
int main(void)
{
	s32 Status = XST_FAILURE;
	XMailbox MailboxInstance;

#ifdef XASU_CACHE_DISABLE
	Xil_DCacheDisable();
#endif

	/** Initialize mailbox instance. */
	Status = (s32)XMailbox_Initialize(&MailboxInstance, XPAR_XIPIPSU_0_BASEADDR);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("Mailbox initialize failed: %08x \r\n", Status);
		goto END;
	}

	Status = XAsu_ClientInit(&MailboxInstance);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("Client initialize failed:%08x \r\n", Status);
		goto END;
	}

	Status = XAsu_MldsaExample();
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-DSA example failed");
	}

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function signs a message with the fixed ML-DSA-44 private key and verifies the
 *		signature against the matching public key.
 *
 * @return
 *		- XST_SUCCESS if the sign and verify both succeed.
 *		- Error code otherwise.
 *
 *************************************************************************************************/
static s32 XAsu_MldsaExample(void)
{
	s32 Status = XST_FAILURE;
	XAsu_ClientParams ClientParams = {0U};
	XAsu_MldsaSignVerifyParams SignParams = {0U};
	XAsu_MldsaSignVerifyParams VerifyParams = {0U};

	/** Common client parameters used for every request. */
	ClientParams.Priority = XASU_PRIORITY_HIGH;
	ClientParams.SecureFlag = XASU_CMD_SECURE;
	ClientParams.CallBackFuncPtr = (XAsuClient_ResponseHandler)((void *)XAsu_MldsaCallBackRef);
	ClientParams.CallBackRefPtr = (void *)&ClientParams;
	ClientParams.AdditionalStatus = XST_FAILURE;

	/**
	 * Sign the test message with the fixed private key (pure ML-DSA, hedged, no context).
	 * ShaType and ShaMode stay at zero: FIPS 204 only uses them for HashML-DSA.
	 */
	SignParams.ParamSet = (u8)XASU_MLDSA_44;
	SignParams.SignMode = (u8)XASU_MLDSA_SIGN_MODE_PURE;
	SignParams.Deterministic = (u8)XASU_MLDSA_HEDGED;
	SignParams.KeyAddr = (u64)(UINTPTR)XAsu_MldsaPrivKey;
	SignParams.KeyLen = XASU_MLDSA_44_PRIV_KEY_LEN;
	SignParams.MsgAddr = (u64)(UINTPTR)XAsu_MldsaMessage;
	SignParams.MsgLen = XASU_MLDSA_EXAMPLE_MSG_LEN;
	SignParams.ContextAddr = 0U;
	SignParams.ContextLen = 0U;
	SignParams.SignatureAddr = (u64)(UINTPTR)XAsu_MldsaSignature;
	SignParams.SignatureLen = XASU_MLDSA_44_SIGN_LEN;

	Status = XAsu_MldsaSign(&ClientParams, &SignParams);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("\r\n ML-DSA Sign request failed with Status = %08x", Status);
		goto END;
	}
	Status = XAsu_MldsaWaitForResponse();
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-DSA Sign failed on server = %08x", ErrorStatus);
		goto END;
	}

	/** Verify the produced signature against the fixed public key. */
	VerifyParams.ParamSet = (u8)XASU_MLDSA_44;
	VerifyParams.SignMode = (u8)XASU_MLDSA_SIGN_MODE_PURE;
	VerifyParams.KeyAddr = (u64)(UINTPTR)XAsu_MldsaPubKey;
	VerifyParams.KeyLen = XASU_MLDSA_44_PUB_KEY_LEN;
	VerifyParams.MsgAddr = (u64)(UINTPTR)XAsu_MldsaMessage;
	VerifyParams.MsgLen = XASU_MLDSA_EXAMPLE_MSG_LEN;
	VerifyParams.ContextAddr = 0U;
	VerifyParams.ContextLen = 0U;
	VerifyParams.SignatureAddr = (u64)(UINTPTR)XAsu_MldsaSignature;
	VerifyParams.SignatureLen = XASU_MLDSA_44_SIGN_LEN;

	Status = XAsu_MldsaVerify(&ClientParams, &VerifyParams);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("\r\n ML-DSA Verify request failed with Status = %08x", Status);
		goto END;
	}
	Status = XAsu_MldsaWaitForResponse();
	/**
	 * A signature counts as verified only when the server status and the redundant verified
	 * indicator both say so, so that a single glitched value cannot pass a bad signature.
	 */
	if ((Status != XST_SUCCESS) ||
	    (ClientParams.AdditionalStatus != XASU_MLDSA_SIGNATURE_VERIFIED)) {
		xil_printf("\r\n ML-DSA Verify failed on server = %08x, additional status = %08x",
			   ErrorStatus, ClientParams.AdditionalStatus);
		Status = XST_FAILURE;
		goto END;
	}

	xil_printf("\r\n Successfully ran ML-DSA Sign/Verify example");

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function blocks until the client library notifies request completion and
 *		returns the server-reported status.
 *
 * @return
 *		- XST_SUCCESS if the server reported success.
 *		- ErrorStatus reported by the server otherwise.
 *
 *************************************************************************************************/
static s32 XAsu_MldsaWaitForResponse(void)
{
	while (!Notify);
	Notify = 0U;

	return (s32)ErrorStatus;
}

/*************************************************************************************************/
/**
 * @brief	Callback function registered with the client library to notify request completion.
 *
 * @param	CallBackRef	Pointer to the callback reference.
 * @param	Status		Status of the request passed as an argument during the callback:
 *			- 0 upon success.
 *			- Error code from the ASUFW application upon any error.
 *
 *************************************************************************************************/
static void XAsu_MldsaCallBackRef(void *CallBackRef, u32 Status)
{
	(void)CallBackRef;

	ErrorStatus = Status;
	/** Update the variable to notify the callback. */
	Notify = 1U;
}
