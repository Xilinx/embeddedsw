/*************************************************************************************************/
/**
 * @brief	This function decapsulates the fixed ACVP ciphertext and compares the shared
 *		secret against the expected one, then encapsulates to the fixed ML-KEM-512
 *		encapsulation key, decapsulates that ciphertext with the matching decapsulation
 *		key and compares both shared secrets.
 *
 * @return
 *		- XST_SUCCESS if the ACVP secret is reproduced and the round trip matches.
 *		- Error code otherwise.
 *
 *************************************************************************************************/
static s32 XAsu_MlkemExample(void)
{
	s32 Status = XST_FAILURE;
	XAsu_ClientParams ClientParams = {0U};
	XAsu_MlkemEncapsDecapsParams EncapsParams = {0U};
	XAsu_MlkemEncapsDecapsParams DecapsParams = {0U};

	/** Common client parameters used for every request. */
	ClientParams.Priority = XASU_PRIORITY_HIGH;
	ClientParams.SecureFlag = XASU_CMD_SECURE;
	ClientParams.CallBackFuncPtr = (XAsuClient_ResponseHandler)((void *)XAsu_MlkemCallBackRef);
	ClientParams.CallBackRefPtr = (void *)&ClientParams;
	ClientParams.AdditionalStatus = XST_FAILURE;

	/**
	 * Step 1: reproduce the ACVP shared secret. Decapsulating the fixed ACVP ciphertext is the
	 * only check here whose expected answer does not come from the example itself, so it runs
	 * first. If it fails, decapsulation is wrong, and the round trip would only show that the
	 * two directions are wrong in the same way.
	 */
	DecapsParams.ParamSet = (u8)XASU_MLKEM_512;
	DecapsParams.KeyAddr = (u64)(UINTPTR)XAsu_MlkemPrivKey;
	DecapsParams.KeyLen = XASU_MLKEM_512_PRIV_KEY_LEN;
	DecapsParams.CtAddr = (u64)(UINTPTR)XAsu_MlkemKatCt;
	DecapsParams.CtLen = XASU_MLKEM_512_CT_LEN;
	DecapsParams.SharedSecretAddr = (u64)(UINTPTR)XAsu_MlkemSharedSecretKat;
	DecapsParams.SharedSecretLen = XASU_MLKEM_SHARED_SECRET_LEN;

	Status = XAsu_MlkemDecapsulate(&ClientParams, &DecapsParams);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("\r\n ML-KEM known answer Decapsulate request failed with Status = "
			      "%08x", Status);
		goto END;
	}
	Status = XAsu_MlkemWaitForResponse();
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-KEM known answer Decapsulate failed on server = %08x",
			   ErrorStatus);
		goto END;
	}

	Status = Xil_SMemCmp(XAsu_MlkemSharedSecretKat, XASU_MLKEM_SHARED_SECRET_LEN,
			     XAsu_MlkemExpSharedSecret, XASU_MLKEM_SHARED_SECRET_LEN,
			     XASU_MLKEM_SHARED_SECRET_LEN);
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-KEM shared secret differs from the ACVP expected secret");
		goto END;
	}

	/**
	 * Step 2: encapsulate to the fixed encapsulation key, producing a ciphertext and shared
	 * secret. This cannot be checked against the vector: the randomness encapsulation draws is
	 * internal to the server, so the ciphertext and secret differ on every run and no expected
	 * value exists for them. The round trip in step 3 is what exercises this direction.
	 */
	EncapsParams.ParamSet = (u8)XASU_MLKEM_512;
	EncapsParams.KeyAddr = (u64)(UINTPTR)XAsu_MlkemPubKey;
	EncapsParams.KeyLen = XASU_MLKEM_512_PUB_KEY_LEN;
	EncapsParams.CtAddr = (u64)(UINTPTR)XAsu_MlkemCt;
	EncapsParams.CtLen = XASU_MLKEM_512_CT_LEN;
	EncapsParams.SharedSecretAddr = (u64)(UINTPTR)XAsu_MlkemSharedSecretEnc;
	EncapsParams.SharedSecretLen = XASU_MLKEM_SHARED_SECRET_LEN;

	Status = XAsu_MlkemEncapsulate(&ClientParams, &EncapsParams);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("\r\n ML-KEM Encapsulate request failed with Status = %08x", Status);
		goto END;
	}
	Status = XAsu_MlkemWaitForResponse();
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-KEM Encapsulate failed on server = %08x", ErrorStatus);
		goto END;
	}

	/**
	 * Step 3: decapsulate the ciphertext from step 2, with the same key and lengths as step 1,
	 * so only the ciphertext read and the secret written change.
	 */
	DecapsParams.CtAddr = (u64)(UINTPTR)XAsu_MlkemCt;
	DecapsParams.SharedSecretAddr = (u64)(UINTPTR)XAsu_MlkemSharedSecretDec;

	Status = XAsu_MlkemDecapsulate(&ClientParams, &DecapsParams);
	if (Status != XST_SUCCESS) {
		XilAsu_Printf("\r\n ML-KEM Decapsulate request failed with Status = %08x", Status);
		goto END;
	}
	Status = XAsu_MlkemWaitForResponse();
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-KEM Decapsulate failed on server = %08x", ErrorStatus);
		goto END;
	}

	/** Confirm the encapsulated and decapsulated shared secrets match. */
	Status = Xil_SMemCmp(XAsu_MlkemSharedSecretEnc, XASU_MLKEM_SHARED_SECRET_LEN,
			     XAsu_MlkemSharedSecretDec, XASU_MLKEM_SHARED_SECRET_LEN,
			     XASU_MLKEM_SHARED_SECRET_LEN);
	if (Status != XST_SUCCESS) {
		xil_printf("\r\n ML-KEM shared secret mismatch");
		goto END;
	}

	xil_printf("\r\n Successfully ran ML-KEM example (ACVP known answer and round trip)");

END:
	return Status;
}

/*************************************************************************************************/
/**
 * @brief	This function blocks until the client library notifies request completion and
 *		returns the server-reported status.
 *
 * @return
 *		- XST_SUCCESS if the server reported success.
 *		- ErrorStatus reported by the server otherwise.
 *
 *************************************************************************************************/
static s32 XAsu_MlkemWaitForResponse(void)
{
	while (!Notify);
	Notify = 0U;

	return (s32)ErrorStatus;
}

/*************************************************************************************************/
/**
 * @brief	Callback function registered with the client library to notify request completion.
 *
 * @param	CallBackRef	Pointer to the callback reference.
 * @param	Status		Status of the request passed as an argument during the callback:
 *			- 0 upon success.
 *			- Error code from the ASUFW application upon any error.
 *
 *************************************************************************************************/
static void XAsu_MlkemCallBackRef(void *CallBackRef, u32 Status)
{
	(void)CallBackRef;

	ErrorStatus = Status;
	/** Update the variable to notify the callback. */
	Notify = 1U;
}
